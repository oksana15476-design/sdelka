import { defineConfig } from 'vitest/config';

/**
 * Интеграционный набор сквозного контура: шаги мира против **живого** Postgres.
 *
 * Запускается только явно — `pnpm --filter @sdelka/e2e test:int` со строкой
 * подключения в `SDELKA_DATABASE_URL`. В `vitest.config.ts` (офлайн-набор)
 * перечень файлов сужен до `test/*.test.ts` ровно ради этого: корневой
 * `pnpm -r test` обязан оставаться бессетевым.
 *
 * Пропуск, когда базы нет, — **громкий и узкий**, и заведён он не здесь: его
 * граница уже проведена в `packages/db/test/int/support/pg.ts` (пропуск только
 * при недоступной базе, падение при любой другой причине), и этот набор берёт
 * ту же, а не заводит вторую.
 *
 * Плагина подмены guard'ов здесь нет намеренно: мутационный прогон живёт в
 * `scripts/mutation.vitest.config.ts` и идёт по офлайн-сценариям. Ломать guard
 * домена на живой базе — значит писать в неё заведомо неверное состояние.
 */
export default defineConfig({
  test: {
    include: ['test/int/**/*.int.test.ts'],
    /*
     * База одна на весь набор, и записанное одним файлом видно другому:
     * параллельные файлы делили бы один журнал учёта. Последовательный прогон
     * здесь дешевле изоляции по схемам — тот же выбор, что в `packages/db`.
     */
    fileParallelism: false,
    testTimeout: 30_000,
    hookTimeout: 60_000,
  },
});
