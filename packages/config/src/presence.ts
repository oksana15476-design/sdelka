/**
 * Три состояния переменной, а не два.
 *
 * «Задана / не задана» — недостаточное различение. Переменная, подставленная
 * пустой (не подхватился секрет из хранилища, пустая строка в манифесте,
 * `export FOO=` в скрипте), для булевой проверки выглядит как незаданная — и
 * человек, который её **уже завёл**, читает «переменной нет» и ищет опечатку в
 * имени, которого там нет. Поэтому пустое значение — своё состояние со своим
 * ключом ошибки.
 */
export const Presence = {
  /** Задана и непуста. */
  present: 'present',
  /** Ключа в окружении нет. */
  absent: 'absent',
  /**
   * Ключ есть, значения нет: пустая строка или одни пробелы.
   *
   * Пробелы считаются пустотой намеренно. Значение из одних пробелов не бывает
   * осмысленным ни для одной переменной перечня (строка подключения, пароль,
   * путь, порт, имя цели стенда), а получается оно ровно тем же способом, что и
   * пустая строка, — подстановкой, которая не сработала. Обратный выбор
   * («пробел — это значение») означал бы попытку подключиться к базе по адресу
   * из пробела и разбираться уже по таймауту драйвера.
   */
  blank: 'blank',
} as const;

export type Presence = (typeof Presence)[keyof typeof Presence];

/**
 * Состояние одной переменной. Возвращает состояние, а не значение: у функции,
 * которая решает «есть ли», не должно быть повода держать секрет в руках.
 */
export function presenceOf(env: NodeJS.ProcessEnv, name: string): Presence {
  const raw = env[name];
  if (raw === undefined) return Presence.absent;
  return raw.trim().length === 0 ? Presence.blank : Presence.present;
}
