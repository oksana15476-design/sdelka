/**
 * Коды ошибок настройки окружения — технические ключи для того, кто
 * разворачивает, а не текст для клиента. Пользовательские формулировки живут в
 * словарях локализации (CLAUDE.md, «Три языка»); сюда клиент не смотрит никогда.
 *
 * **В `details` попадают только имена переменных.** Значение переменной не
 * попадает в ошибку ни при каких обстоятельствах: сообщение об ошибке уезжает в
 * журнал, журнал уезжает в сборщик логов, и секрет, показанный «один раз при
 * старте», оказывается в трёх местах сразу (красная линия №12).
 */
export const ConfigErrorCode = {
  /**
   * Проверка на старте не прошла: какой-то обязательной переменной нет или она
   * пуста. Одна ошибка на весь набор, а не по одной на переменную — тот, кто
   * разворачивает, должен увидеть **весь** список за один заход, а не чинить по
   * штуке, перезапуская процесс между исправлениями.
   */
  envIncomplete: 'config.env.incomplete',
  /** Переменной в окружении нет вовсе: ключ отсутствует. */
  envAbsent: 'config.env.absent',
  /**
   * Переменная задана и пуста (или состоит из пробелов). Отдельный ключ, а не
   * тот же, что у отсутствия: человек, увидевший «переменной нет», идёт её
   * заводить, а он её уже завёл — и ищет опечатку не там. Разница между «забыл»
   * и «подставилось пустым» — это разница между забытой строкой в манифесте и
   * не подхватившимся секретом из хранилища.
   */
  envBlank: 'config.env.blank',
  /** Две записи перечня под одним именем: перечень перестал быть перечнем. */
  registryDuplicate: 'config.registry.duplicate',
  /** Спросили про имя, которого в перечне нет. */
  registryUnknown: 'config.registry.unknown',
  /**
   * Строку подключения не удалось разобрать, поэтому она **не печатается**.
   * Неразобранная строка возвращается этим ключом, а не собой: «покажу как
   * есть, раз не понял» — это и есть способ напечатать пароль.
   */
  redactUnparsable: 'config.redact.unparsable',
} as const;

export type ConfigErrorCode = (typeof ConfigErrorCode)[keyof typeof ConfigErrorCode];

export class ConfigError extends Error {
  readonly code: ConfigErrorCode;
  readonly details: Readonly<Record<string, string>>;

  constructor(code: ConfigErrorCode, details: Readonly<Record<string, string>> = {}) {
    super(code);
    this.name = 'ConfigError';
    this.code = code;
    this.details = details;
  }
}
