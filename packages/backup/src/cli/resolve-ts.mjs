/**
 * Разрешение относительных импортов **без расширения** для запуска команд
 * напрямую в node.
 *
 * ⚠ Это обход, а не решение, и место ему здесь только потому, что причина
 * лежит в чужих пакетах. `@sdelka/audit` и `@sdelka/ledger` написаны с
 * импортами вида `export * from './anchor'` — так их разрешает сборщик
 * приложения, но не node: в ESM расширение обязательно. Пока это так, любая
 * команда, дотягивающаяся до учёта или журнала аудита, падает при запуске с
 * `ERR_MODULE_NOT_FOUND` — то есть **`dump` и `verify` не запускались вовсе**,
 * и заметить это можно было только в день, когда копия понадобилась.
 *
 * Хук ничего не «угадывает»: он вступает в дело **только** после того, как
 * штатное разрешение уже отказало, и только для относительного пути, дописывая
 * ровно одно расширение. Импорт, который не разрешается и с ним, отдаёт
 * исходную ошибку — подмена одного отказа другим здесь была бы хуже отказа.
 *
 * Настоящее решение — расширения в исходниках `@sdelka/audit` и
 * `@sdelka/ledger`. Оно за границей этого пакета; после него хук снимается
 * вместе с этим файлом, и ничего, кроме него, снимать не придётся.
 */
export async function resolve(specifier, context, nextResolve) {
  try {
    return await nextResolve(specifier, context);
  } catch (error) {
    if (!specifier.startsWith('.') || /\.[cm]?[jt]sx?$/u.test(specifier)) throw error;
    try {
      return await nextResolve(`${specifier}.ts`, context);
    } catch {
      throw error;
    }
  }
}
