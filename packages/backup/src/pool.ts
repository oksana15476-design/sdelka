import { configureTypeParsers } from '@sdelka/db';
import pg from 'pg';

/**
 * Пул для снятия копии — **со своими сроками**, и это не дубль `createPool` из
 * `@sdelka/db`.
 *
 * Сроки там подобраны под приложение и под интеграционный набор: запрос дольше
 * пятнадцати секунд — это ожидание блокировки, транзакция, простаивающая
 * дольше тридцати, — зависший тест. Снятие копии нарушает обе посылки сразу и
 * по построению:
 *
 * - сессия, экспортировавшая снимок, **обязана простаивать** ровно столько,
 *   сколько работает `pg_dump`. На боевом объёме это минуты и десятки минут.
 *   С `idle_in_transaction_session_timeout = 30s` сервер убил бы её посреди
 *   снятия, а `pg_dump` упал бы с потерей снимка — то есть копия не снималась
 *   бы вовсе ровно тогда, когда база доросла до размера, при котором копия
 *   и нужна;
 * - перепись (`census.ts`) считает `count(*)` по всем таблицам схемы и
 *   поднимает журнал учёта целиком. Это законно долго.
 *
 * Поэтому серверные сроки здесь сняты (`0` — «без предела»), а клиентские не
 * задаются вовсе. Остаётся только срок **соединения**: недоступная база обязана
 * называться недоступной за секунды, а не выглядеть как зависшее снятие.
 *
 * Разборщики типов те же, что у приложения (`configureTypeParsers`): красная
 * линия №4 переживает границу процесса только через них, и перепись, читающая
 * суммы `number`-ом, врала бы о сходимости журнала на больших числах.
 */
export const BACKUP_CONNECT_TIMEOUT_MS = 10_000;

export function backupPool(connectionString: string): pg.Pool {
  configureTypeParsers();
  return new pg.Pool({
    connectionString,
    connectionTimeoutMillis: BACKUP_CONNECT_TIMEOUT_MS,
    // Пределы сняты намеренно — разбор выше. Заданы **явно**, а не пропущены:
    // сервер может нести их в `ALTER ROLE ... SET`, и молчаливое наследование
    // вернуло бы ту же смерть посреди снятия, только необъяснимую.
    statement_timeout: 0,
    idle_in_transaction_session_timeout: 0,
    // Пул на одно соединение: снимок экспортирует **одна** сессия, и вторая,
    // взятая по недосмотру, видела бы другие данные.
    max: 1,
  });
}

export type { Pool, PoolClient } from 'pg';
