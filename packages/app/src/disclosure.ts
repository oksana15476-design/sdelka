import {
  type AuditRef,
  type NonEmpty,
  appendRecord,
  auditInstant,
  auditRef,
} from '@sdelka/audit';
import { type Authority, assertOrigin, journalActor } from './authority';
import { auditRecordId } from './ids';
import { type World, sealed } from './world';

/**
 * Раскрытие персональных данных — путь из продукта в вечный журнал.
 *
 * ## Зачем модуль появился
 *
 * `FUNCTIONAL.md` инвариант 24 обещает: «просмотр документа и персональных
 * данных логируется». Механизм под это обещание был построен целиком — вид
 * записи `personal_data_viewed` в `AUDIT_RECORD_KINDS`, тело
 * `PersonalDataViewedBody`, метка `personal_data_viewed` в перечне
 * `sdelka.audit_record_kind` (`0001_foundation.sql`), — и **пишущего не было
 * ни одного**: grep по всем `src` давал объявление вида и комментарий о нём.
 * То есть дорога к механизму отсутствовала, а инвариант 24 — не наша
 * внутренняя дисциплина, а обязанность перед субъектом персональных данных:
 * пока записи нет, ответить на запрос «кто смотрел мои документы» нечем.
 *
 * ## Что здесь считается просмотром, и почему именно это
 *
 * ⚠ **[открыто]** Продуктовый вопрос — что считать просмотром: открытие
 * карточки стороны, раскрытие конкретного поля или выгрузку файла — стоит в
 * `docs/product/DECISIONS-REVIEW.md` §H5 и **решается владельцем**. Три ответа
 * дают три разных объёма вечного журнала и три разных ответа субъекту.
 *
 * Пока ответа нет, реализовано **пересечение всех трёх**: то, что является
 * просмотром при любом из них.
 *
 * 1. **Выгрузка или открытие файла документа** — `releaseDocument`. Файл
 *    отдан пользователю; просмотром это считает любая из трёх трактовок.
 * 2. **Раскрытие персонального поля по явному действию** — `revealPersonalFields`.
 *    Не «поле пришло в ответе сервера», а «пользователь нажал „показать“»:
 *    маска снята, значение показано.
 *
 * Более широкая трактовка — **сам факт открытия карточки** — выражена
 * `notePartyCardOpened` и заперта настройкой `DisclosurePolicy.logCardOpened`
 * со значением по умолчанию **`false`** (`DISCLOSURE_POLICY_DEFAULT`). Умолчание
 * названо явно, а не получено молчанием: включить его — решение владельца по
 * §H5, а не наше. Довод против включения по умолчанию записан в самом
 * `@sdelka/auth`: «`read_deal` при каждом открытии карточки — это шум, который
 * топит журнал и делает его непригодным для того, ради чего он ведётся»
 * (`capabilities.ts`, `CapabilitySpec.journaled`).
 *
 * ## Три свойства, которые здесь держатся конструкцией, а не дисциплиной
 *
 * 1. **Полномочие проверяется до записи и до выдачи данных.** Оба входа
 *    принимают `Authority<DisclosureCapability>` — значение, которое литералом
 *    не собрать: единственный способ его получить — `authorize`, где отработали
 *    сессия, полномочие роли, второй фактор и разделение обязанностей. Нет
 *    полномочия — нет `Authority`, значит нет ни записи, ни данных: выдача
 *    живёт **внутри** этой функции, а не рядом с ней.
 * 2. **Персональных данных в теле записи нет — только ссылки и ключи полей.**
 *    Иначе вечный журнал сам становится хранилищем ПДн, из которого их уже не
 *    убрать ни по требованию субъекта, ни по ошибке (`values.ts`, преамбула).
 *    Поэтому `fields` — перечень из закрытого `PERSONAL_FIELDS`, а не значения,
 *    и субъект записи — ссылка `party`, а не имя.
 * 3. **Запись только дописывается.** Идёт общей дверью `appendRecord` и через
 *    `sealed`, то есть сцепка, монотонность времени, запрет сырых
 *    идентификаторов и целостность цепочки проверяются ровно так же, как у
 *    записей о деньгах. Исправить её нечем: единственный продуктовый путь к
 *    исправлению — `correctPayoutReason`, и он отвергает всё, чей корень не
 *    `payout_result` (`correction.ts`, `app.correction.kind_not_correctable`).
 *
 * ## Чего здесь нет намеренно
 *
 * **Нового полномочия.** Тот же довод, что у `correction.ts`: завести своё
 * значило бы править `CAPABILITIES`, `separationRulesFor`, `roles.ts` и метку
 * перечня `sdelka.capability` одним заходом — то есть решить за владельца
 * вопрос, которого он не ставил. Взяты существующие права на чтение
 * персональных данных (`DISCLOSURE_CAPABILITIES`).
 *
 * **Водяного знака.** `ACTORS.md` §4.1 A3 и «Видимость» требуют показывать
 * документ с водяным знаком, несущим идентификатор смотрящего. Это свойство
 * **отдачи файла**, а не журнала: знак накладывает тот, кто готовит байты.
 * Названо, а не спрятано: здесь его нет.
 *
 * **Подключения к экрану.** `apps/web` сегодня — прототип на фикстурах: ни
 * одного обработчика маршрута, ни одного серверного действия, и зависимости от
 * `@sdelka/app` у него нет вовсе. Места, где документ **действительно**
 * отдаётся пользователю, в дереве нет ни одного; когда оно появится, вход —
 * `releaseDocument`, и другого не будет.
 */

/* ------------------------------------------------------------------------- */
/* Чем раскрытие разрешается                                                 */
/* ------------------------------------------------------------------------- */

/**
 * Полномочия, под которыми персональные данные вообще могут быть раскрыты.
 *
 * Перечень закрыт и **не содержит `read_deal`**, хотя это и самое ходовое право
 * на чтение. Причина названа в `ACTORS.md` «Видимость»: «владелец открывает
 * сделку — имён сторон в ответе сервера нет». Роль владельца (`principal`) из
 * прав на чтение имеет ровно `read_deal`, и допусти он сюда — раскрытие
 * персональных данных стало бы ему доступно вместе с карточкой сделки.
 *
 * Что вошло и почему:
 * · `read_party` — данные стороны (`ACTORS.md` §4.1);
 * · `read_beneficiary` — реквизиты, даже в виде проекции (§4.2 B3, §8 п.1);
 * · `read_audit` — аудитор читает всё, включая ПДн, «каждое чтение — запись
 *   `personal_data_viewed`» (§6.11);
 * · `export_personal_data` — выдача субъекту по его требованию (§5.1).
 */
export const DISCLOSURE_CAPABILITIES = [
  'read_party',
  'read_beneficiary',
  'read_audit',
  'export_personal_data',
] as const;

export type DisclosureCapability = (typeof DISCLOSURE_CAPABILITIES)[number];

/* ------------------------------------------------------------------------- */
/* Что именно раскрыто                                                       */
/* ------------------------------------------------------------------------- */

/**
 * Персональные поля — **закрытый перечень ключей, а не свободная строка**.
 *
 * Свободная строка на этом месте — это дверь, через которую в вечный журнал
 * попадает значение вместо имени поля: «Иванов» вместо `name`. Проверка
 * `assertNoRawIdentifiers` ловит грубые формы (IBAN, длинные цифровые серии,
 * телефон), но она заведомо неполна и об этом честно сказано в самом
 * `@sdelka/audit`. Перечень закрывает то, чего она поймать не может.
 *
 * Состав взят из уже существующих закрытых перечней проекта, а не придуман:
 * восемь значений — `FINGERPRINT_SUBJECTS` (`@sdelka/audit`) без `raw_source`,
 * который персональным полем не является; `biometrics` и `document_scan`
 * названы `ACTORS.md` §4.1 A3 («биометрия и сканы — специальная категория»).
 */
export const PERSONAL_FIELDS = [
  'name',
  'document_number',
  'personal_number',
  'account',
  'phone',
  'address',
  'device',
  'network_address',
  'biometrics',
  'document_scan',
] as const;

export type PersonalField = (typeof PERSONAL_FIELDS)[number];

/**
 * Общая часть обоих входов.
 *
 * `partyId` — **ссылка на субъект персональных данных**, и ничего кроме: имя
 * стороны, её номер документа и её реквизиты в записи не появляются ни в каком
 * виде. Субъект записи один и тот же у всех раскрытий (`ref_scope` `party`)
 * именно затем, чтобы ответ на запрос «кто смотрел мои документы» был одной
 * выборкой по субъекту, а не сшивался из нескольких областей.
 */
interface Disclosure {
  /** Чьи данные раскрыты. Идентификатор участия, не имя. */
  readonly partyId: string;
  /**
   * Зачем смотрели — ключ локализации (`CLAUDE.md`: ни одной строки
   * пользовательского текста в коде). Пустым быть не может.
   */
  readonly purposeKey: string;
  /** Какие поля раскрыты. Ключи из `PERSONAL_FIELDS`, не значения. */
  readonly fields: NonEmpty<PersonalField>;
  /** Связанные предметы: сделка, транш, реквизиты. Ссылки, не содержимое. */
  readonly related?: readonly AuditRef[];
}

/** Выгрузка или открытие файла документа. */
export interface DocumentRelease extends Disclosure {
  /**
   * Документ, который отдан. Идентификатор в хранилище — он попадёт в `related`
   * ссылкой `document`, и по нему видно, **что именно** было отдано.
   */
  readonly documentId: string;
}

/** Раскрытие персонального поля по явному действию пользователя. */
export type FieldReveal = Disclosure;

/** Открытие карточки стороны. Пишется только при включённой настройке. */
export type CardOpening = Disclosure;

/**
 * Что вернулось пользователю вместе с записью о том, что оно вернулось.
 *
 * Мир и выданное значение отдаются **одним значением** намеренно: раздельные
 * вызовы «запиши» и «отдай» — это два места, которые можно позвать по
 * отдельности, и тогда инвариант 24 снова держится дисциплиной вызывающего.
 */
export interface Released<T> {
  readonly world: World;
  readonly released: T;
}

/* ------------------------------------------------------------------------- */
/* Настройка широкой трактовки                                               */
/* ------------------------------------------------------------------------- */

/**
 * Считать ли просмотром сам факт открытия карточки стороны.
 *
 * ⚠ **[открыто], `DECISIONS-REVIEW.md` §H5.** Ответ за владельцем, и до него
 * значение по умолчанию — `false`, названное здесь явно. Ни выгрузки файла, ни
 * раскрытия поля это не касается: они пишутся всегда, потому что просмотром их
 * считает любая из трёх трактовок.
 */
export interface DisclosurePolicy {
  readonly logCardOpened: boolean;
}

export const DISCLOSURE_POLICY_DEFAULT: DisclosurePolicy = Object.freeze({
  logCardOpened: false,
});

/* ------------------------------------------------------------------------- */
/* Запись                                                                    */
/* ------------------------------------------------------------------------- */

const KNOWN_FIELDS: ReadonlySet<string> = new Set<string>(PERSONAL_FIELDS);

function checkedFields(request: Disclosure, what: string): NonEmpty<PersonalField> {
  const seen = new Set<string>();
  for (const field of request.fields) {
    if (!KNOWN_FIELDS.has(field)) {
      // Тип это уже отверг бы, но перечень полей может приехать значением
      // из-за границы процесса — тот же довод, по которому `assertOrigin`
      // дублирует компиляционный рубеж происхождения.
      throw new Error(`app.disclosure.unknown_field:${what}:${String(field)}`);
    }
    if (seen.has(field)) {
      // Одно и то же поле дважды в одной записи — шум в вечном журнале.
      throw new Error(`app.disclosure.duplicate_field:${what}:${field}`);
    }
    seen.add(field);
  }
  return request.fields;
}

/**
 * Дописать запись о раскрытии.
 *
 * Наружу не выходит: единственные входы — три функции ниже, и каждая объявляет,
 * **что** было раскрыто. Свободный писатель на этом месте позволил бы записать
 * раскрытие, которого не было, — и отличить такую запись от настоящей через год
 * было бы нечем.
 */
function appendDisclosure(
  world: World,
  request: Disclosure,
  authority: Authority<DisclosureCapability>,
  what: string,
  related: readonly AuditRef[],
): World {
  assertOrigin(DISCLOSURE_CAPABILITIES, authority, what);
  if (request.purposeKey.length === 0) {
    // Раскрытие без основания — это доступ, у которого нет объяснения. Пустую
    // строку не примет и сама запись (`AUDIT_TOKEN`); отказ здесь только
    // называет её на языке шага.
    throw new Error(`app.disclosure.purpose_required:${what}:${request.partyId}`);
  }
  const fields = checkedFields(request, what);
  const seq = world.seq + 1;
  return sealed({
    ...world,
    seq,
    chain: appendRecord(world.chain, {
      recordId: auditRecordId(world.chain.chainId, seq),
      recordedAt: auditInstant(world.now),
      actor: journalActor(authority),
      // Субъект — тот, чьи данные раскрыли, а не тот, кто смотрел: смотрящий
      // стоит актором записи (`journalActor`), и назвать его вызывающий не
      // может — он выводится из сессии.
      subject: auditRef('party', request.partyId),
      related,
      body: {
        kind: 'personal_data_viewed',
        purposeKey: request.purposeKey,
        fields,
      },
    }),
    checks: world.checks,
  });
}

function relatedOf(request: Disclosure, head: readonly AuditRef[]): readonly AuditRef[] {
  return Object.freeze([...head, ...(request.related ?? [])]);
}

