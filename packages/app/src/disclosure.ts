/**
 * Отдать файл документа — и записать, что он отдан.
 *
 * Порядок именно такой: **сначала запись, потом выдача**. Обратный порядок
 * означал бы, что сбой при записи оставляет документ отданным и незалогированным
 * — то есть ровно тот случай, ради которого инвариант 24 существует.
 *
 * ⚠ **Граница применимости `deliver`.** Он обязан **произвести значение**, а не
 * начать его отдавать: потоковая выдача, упавшая на середине, оставила бы
 * запись о показанном документе, часть которого до пользователя не дошла, — но
 * это меньшее зло, чем дошедший документ без записи. Если `deliver` бросает,
 * возвращённого мира у вызывающего не оказывается, и запись вместе с ним
 * теряется: ничего не отдано — ничего не записано. Названо здесь, а не
 * подразумевается.
 */
export function releaseDocument<T>(
  world: World,
  request: DocumentRelease,
  authority: Authority<DisclosureCapability>,
  deliver: () => T,
): Released<T> {
  const next = appendDisclosure(
    world,
    request,
    authority,
    'disclosure.document',
    relatedOf(request, [auditRef('document', request.documentId)]),
  );
  return { world: next, released: deliver() };
}

/**
 * Снять маску с персонального поля по явному действию пользователя — и записать
 * это.
 *
 * «Явное действие» — не оговорка стиля, а условие применимости: поле, пришедшее
 * в ответе сервера вместе с карточкой, сюда не относится (это широкая трактовка
 * §H5, см. `notePartyCardOpened`). Здесь — нажатие «показать»: маска снята,
 * значение показано.
 */
export function revealPersonalFields<T>(
  world: World,
  request: FieldReveal,
  authority: Authority<DisclosureCapability>,
  reveal: () => T,
): Released<T> {
  const next = appendDisclosure(
    world,
    request,
    authority,
    'disclosure.field',
    relatedOf(request, []),
  );
  return { world: next, released: reveal() };
}

/**
 * Отметить открытие карточки стороны — **если владелец решил, что это просмотр**.
 *
 * ⚠ **[открыто], `DECISIONS-REVIEW.md` §H5.** При `logCardOpened === false`
 * (умолчание) мир возвращается неизменным: записи нет. Данных эта функция не
 * выдаёт и выдачу не сторожит — открытие карточки идёт своим путём под
 * `read_party`, и так оно устроено сегодня. Настройка включает **только
 * журналирование**, потому что вопрос §H5 ровно об объёме журнала, а не о
 * доступе.
 *
 * Полномочие проверяется **до** ветвления по настройке: выключенная настройка
 * не должна быть способом отметить открытие карточки без права её открыть.
 */
export function notePartyCardOpened(
  world: World,
  request: CardOpening,
  authority: Authority<DisclosureCapability>,
  policy: DisclosurePolicy,
): World {
  assertOrigin(DISCLOSURE_CAPABILITIES, authority, 'disclosure.card');
  if (!policy.logCardOpened) {
    return world;
  }
  return appendDisclosure(
    world,
    request,
    authority,
    'disclosure.card',
    relatedOf(request, []),
  );
}
