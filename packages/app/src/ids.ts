/**
 * Идентификаторы вечных записей: журнал учёта и журнал аудита.
 *
 * **Почему это отдельный модуль.** Форма идентификатора — не деталь места, где
 * запись чеканится, а свойство таблицы, в которой она будет лежать вечно.
 * Мест чеканки шесть (`flow.ts` — пять, `withdrawal.ts` — одно, у журнала
 * аудита ещё и `unwind.ts` с `correction.ts`), и пока форма была вписана в
 * каждое из них строкой, расходиться ей было нечем — но и **чинить** её
 * пришлось бы в каждом. Так и вскрылось: у журнала аудита идентификатор нёс
 * цепочку (`${chainId}:r${seq}`), у журнала учёта — не нёс ничего
 * (`entry-${seq}-${label}`), и заметить это можно было только сложив шесть
 * строк из четырёх файлов.
 *
 * **Что чинится.** `seq` — счётчик **мира**, и начинается он с нуля в каждом
 * новом мире (`emptyWorld`). Пока хранилище было картой в памяти, у каждого
 * теста была своя карта, и счётчики не встречались. Живая таблица одна и
 * вечная: два мира в одной базе сталкивались на `entry-1-top-up` — второй мир
 * получал `db.step.conflict` на `ledger_entry` и не доходил до первой денежной
 * записи. Цепочка аудита в идентификаторе — это и есть область имён, которой
 * записи журнала учёта не хватало.
 *
 * **Почему цепочка, а не время и не случайность.** Идентификатор обязан быть
 * воспроизводимым: повтор того же шага из того же мира обязан дать те же
 * строки, иначе хранилище не отличит повтор от второй записи, а восстановление
 * истории перестанет сходиться с записанным. Ни системных часов, ни
 * случайности здесь поэтому нет — только то, что мир уже про себя знает:
 * цепочка и порядковый номер.
 *
 * **Почему `e` и `r` не сталкиваются.** Счётчик у записей журнала учёта и
 * записей журнала аудита **один** (`World.seq`), поэтому одно и то же `seq` в
 * одной цепочке достаётся ровно одной записи. Различающая буква стоит всё
 * равно: она делает вид записи читаемым в отказе базы, где кроме
 * идентификатора часто нет ничего.
 *
 * **Перезапуск процесса.** Прежняя редакция называла его среди
 * непочиненного: `seq` поднятого мира взять было неоткуда, потому что поднятый
 * мир не продолжался вовсе. Теперь продолжается (`resume.ts`), и счётчик берётся
 * **из записанного** — `seqOfEternalId` разбирает те же идентификаторы, которые
 * чеканят функции ниже. Разбор живёт здесь же по той причине, по которой здесь
 * живёт чеканка: две половины одной формы, разъехавшись, дали бы поднятый мир,
 * который пишет поверх собственных строк.
 */

/** Идентификатор записи журнала аудита: цепочка и номер. */
export function auditRecordId(chainId: string, seq: number): string {
  return `${chainId}:r${seq}`;
}

/**
 * Идентификатор записи журнала учёта: та же цепочка, тот же номер, метка вида.
 *
 * Метка — не ключ локализации и не текст для клиента: она попадает только в
 * идентификатор строки и в отказы хранилища. Смысл записи несёт `memoKey`.
 */
export function journalEntryId(chainId: string, seq: number, label: string): string {
  return `${chainId}:e${seq}-${label}`;
}

/**
 * Начало идентификатора записи журнала учёта этой цепочки.
 *
 * Отсюда его берёт охват чтения журнала (`store.ts`, `JournalScope`): хранилищу
 * форма идентификатора не известна и известна быть не должна, а известна она
 * этому модулю — тому же, который её чеканит.
 *
 * ⚠ **Отбор по началу строки — грубый, и назван грубым.** Двоеточие алфавит
 * идентификатора цепочки допускает (`0007_audit.sql`, `chain_id ~
 * '^[A-Za-z0-9][A-Za-z0-9_.:/+=~-]*$'`), поэтому цепочка `a` и цепочка `a:e1`
 * началами не различаются, и хранилище, отбирающее по началу, отдаёт **надмножество**.
 * Точное правило — `seqOfEternalId` ниже: в номере записи двоеточия быть не
 * может, поэтому чужая строка на разборе отсеивается. Поэтому подъём мира
 * (`store.ts`, `restoreWorld`) отбирает разбором, а не началом строки: одинаково
 * при любой реализации порта.
 */
export function journalEntryIdPrefix(chainId: string): string {
  return `${chainId}:e`;
}

/**
 * Номер мира, которым запись была отчеканена, — из самого идентификатора.
 *
 * `null` означает «запись не этой цепочки либо чеканена не здесь»: чужую строку
 * поднятый мир в свой счётчик не берёт, а неразобранную — тем более. Ошибкой это
 * не является: в общей таблице живут записи всех миров, и отбирать свои — прямая
 * задача вызывающего.
 *
 * Разбирает обе формы, `:r{seq}` и `:e{seq}-{метка}`, потому что счётчик у них
 * **один** (`World.seq`): продолжающий мир обязан начать со следующего за
 * наибольшим из обоих журналов, иначе первая же его запись встретит свою.
 */
export function seqOfEternalId(chainId: string, id: string): number | null {
  const prefix = `${chainId}:`;
  if (!id.startsWith(prefix)) return null;
  const rest = id.slice(prefix.length);
  const kind = rest.slice(0, 1);
  if (kind !== 'e' && kind !== 'r') return null;
  // У записи журнала учёта за номером идёт метка вида, у записи журнала аудита
  // не идёт ничего. Черта в метке допустима, поэтому берётся первая часть.
  const digits = rest.slice(1).split('-')[0] ?? '';
  if (!/^[0-9]+$/.test(digits)) return null;
  return Number(digits);
}
