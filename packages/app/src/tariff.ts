import type { Instant, Result } from '@sdelka/domain';
import type { CurrencyCode, Money } from '@sdelka/money';
import {
  type PricingRefusalKey,
  type TariffQuotation,
  type TariffSeries,
  quoteTrancheTariff,
} from '@sdelka/pricing';
import type { SettingsRefusalKey, SettingsVersionId } from '@sdelka/settings';

/**
 * Дорога от журнала версий тарифа до транша.
 *
 * **Находка, которую этот файл закрывает.** `packages/pricing` был построен и
 * не импортировался ниоткуда: приложение клало `tariffVersionId` обычной
 * строкой (проверяемой только на отсутствие `:` и `|`) и брало удержания из
 * отдельного поля `deductions`. Две величины, которые обязаны приходить из
 * одной версии, приходили из разных мест — то есть «посчитать по одной версии,
 * а записать другую» было не ошибкой, а обычным вызовом:
 *
 * ```ts
 * createTranche(world, { deductions: PLATFORM_FEE, tariffVersionId: 'tariff-2026-09-01' })
 * ```
 *
 * Ни одна проверка не связывала эту строку ни с журналом версий, ни с суммой,
 * которую та же запись начисления называет. Ответить по ней на вопрос И14.3
 * «почему списали именно столько» было нечем.
 *
 * **Что стоит теперь.** Тариф транша — это `TariffQuotation`: версия, план,
 * комиссия, брутто, нетто и строка удержания **одним значением**. Получить его
 * иначе, чем разрешив версию на момент создания транша, нельзя — единственный
 * вход `quoteTrancheTariff` требует журнал версий и момент, а момент собирается
 * только из события `tranche_created` (`@sdelka/settings`, `StickingMoment`).
 * Отсюда свойство, ради которого всё это: изменение тарифа не двигает уже
 * заведённые транши — не потому, что мы не пересчитываем, а потому, что
 * пересчитать не по чему.
 *
 * **Чего здесь нет.** Ни одной величины и ни одного расчёта: числа тарифа
 * принадлежат владельцу (`DECISIONS-REVIEW.md` §J, всё **[открыто]**), а
 * арифметика живёт в `@sdelka/pricing`. Ни одного умолчания: пустой журнал
 * версий — отказ, а не «взять `PROVISIONAL_TARIFF_PLAN`». Временное значение
 * существует ровно затем, чтобы **им завели первую версию** журнала, и тогда
 * оно видно в журнале со своим основанием, а не спрятано в коде.
 */

/**
 * Тариф, прилипший к траншу.
 *
 * Псевдоним, а не своя форма: вторая редакция тарификации разошлась бы с первой
 * молча. Валюта здесь широкая (`CurrencyCode`), потому что транш приходит из
 * спецификации, где она не известна на этапе типов; сама котировка при этом
 * собрана в валюте суммы сделки и с планом той же валюты — иначе
 * `quoteTariff` отвечает `planCurrencyNotDeclared`.
 */
export type TrancheTariff = TariffQuotation<CurrencyCode>;

/** Отказ тарификации транша: чужой пакет назвал причину, приложение её не переписывает. */
export type TariffRefusalKey = SettingsRefusalKey | PricingRefusalKey;

/**
 * Тариф на момент создания транша.
 *
 * Тонкая обёртка намеренно: разрешение версии — `@sdelka/settings`, тарификация
 * — `@sdelka/pricing`, и второй их редакции здесь нет. Обёртка существует ради
 * одного: имя, под которым боевой путь зовёт эту дорогу, обязано читаться в
 * `packages/app`, иначе через полгода рядом появится второй вызов с другим
 * моментом.
 */
export function tariffForNewTranche(
  series: TariffSeries,
  createdAt: Instant,
  principal: Money<CurrencyCode>,
): Result<TrancheTariff, TariffRefusalKey> {
  return quoteTrancheTariff(series, createdAt, principal);
}

/**
 * Версия, по которой посчитан этот тариф.
 *
 * Отдельного поля с версией рядом с суммой в приложении больше нет: ссылка
 * берётся **из той же котировки**, из которой берётся комиссия, и подставить
 * сюда чужую нечем — функция принимает котировку целиком, а не строку.
 */
export function tariffVersionOf(tariff: TrancheTariff): SettingsVersionId {
  return tariff.versionId;
}

/**
 * Тариф транша там, где без него нельзя продолжать.
 *
 * `null` бывает ровно у одного транша — поднятого из хранилища: версия тарифа в
 * схеме не лежит (`resume.ts`, `gaps`), и восстановить её неоткуда. Прежде это
 * состояние выглядело как пустой список удержаний, то есть **как нулевая
 * комиссия**: расчёт по поднятому траншу собирался, сходился повалютно и молча
 * дарил клиенту нашу выручку. Теперь это закрытый отказ.
 *
 * Исключение, а не `Result`: тариф не «не сошёлся сегодня», его нет вовсе, и
 * разбирать оператору здесь нечего — чинится подъёмом версии в хранилище
 * (`DECISIONS-REVIEW.md` §J6 **[открыто]**).
 */
export function requireTrancheTariff(trancheId: string, tariff: TrancheTariff | null): TrancheTariff {
  if (tariff === null) {
    throw new Error(`app.tranche.tariff_unknown:${trancheId}`);
  }
  return tariff;
}
