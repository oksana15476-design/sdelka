import { type DurationMs, type Instant, duration } from '@sdelka/domain';
import {
  type IdentityChallenge,
  type IdentityCodePolicy,
  IDENTITY_CODE_POLICY,
  challengeStatus,
  issueChallenge,
} from './challenge';
import type { AccountId, ChallengeId } from './ids';

/**
 * Поток запросов «пришлите код» — **сколько вызовов и сколько отправок стоит за
 * сотней запросов**.
 *
 * ## Что здесь закрывается
 *
 * `IDENTITY_CODE_POLICY` ограничивает подбор **кода**: пять попыток, десять
 * минут, однократность. Поток запросов он не ограничивает ничем: сто запросов
 * подряд по одной учётной записи заводят сто вызовов и сто отправок в канал.
 * Это не дыра в аутентификации — ни один из этих запросов не приближает никого
 * к коду, — но это отказ в обслуживании и наш счёт за отправку сообщений
 * (`DECISIONS-REVIEW.md` §Z2).
 *
 * Взят **вариант Б**: ограничение в домене, не более одного живого вызова на
 * учётную запись, состояние — в самой записи вызова. Вариант А (ограничение на
 * транспорте, по сети и по учётной записи) требует держать счётчики где-то ещё:
 * либо своя таблица, либо новая зависимость. Ни того ни другого здесь не
 * заводится.
 *
 * Уточнение к варианту Б названо в §Z2 ценой: «человек, потерявший первое
 * сообщение, ждёт истечения десяти минут». Так здесь **не** делается. Повторный
 * запрос возвращает **тот же живой вызов** — то есть человек, у которого
 * сообщение задержалось, ссылку не теряет, — а раз в окно повторной отправки
 * тот же самый код уходит в канал ещё раз. Окно защищает счёт за отправку;
 * ждать десять минут при этом не приходится никому.
 *
 * ## Одно правило, из которого следует всё остальное
 *
 * **Не более одной отправки на учётную запись за окно — по любому пути.**
 *
 * Пути три, и throttled обязаны быть все три, иначе ограничения нет вовсе:
 *
 * - живой вызов, окно не вышло → возвращается он же, канал молчит;
 * - живой вызов, окно вышло → тот же вызов, тот же код, отправка повторяется;
 * - живого вызова нет (истёк, израсходован, попытки кончились) → новый вызов —
 *   но **тоже не раньше, чем через окно после последней отправки**. Без этого
 *   ограничение обходится за пять секунд: пять неверных ответов закрывают
 *   вызов, следующий запрос заводит новый и шлёт сообщение, и так до бесконечности.
 *   Заодно это единственное место, где поток запросов упирается в подбор:
 *   сегодня сто запросов дают пятьсот догадок, здесь — пять за окно.
 *
 * Запертым человек при этом не остаётся ни в одном состоянии: закрытый вызов
 * задерживает выдачу нового на **окно**, а не на срок годности кода.
 *
 * ## Ответ снаружи один и тот же
 *
 * Все три исхода отдают `reference` — ссылку той же формы, что и обычный ответ.
 * «Слишком часто» не имеет ни своего отказа, ни своего поля: разный ответ на
 * «слишком часто» и на «держите код» — это способ перечислять учётные записи,
 * не зная ни одного кода (`DECISIONS-REVIEW.md` §Z3, и это же проверяется
 * тестом на равенство ответов в `app/test/sign-in.test.ts`).
 *
 * ⚠ **Одно различие вариант Б всё-таки заводит, и закрыть его отсюда нечем.**
 * Повторный запрос по существующей записи внутри окна возвращает **ту же**
 * ссылку, а по несуществующей — каждый раз новую (`sign-in.ts`: ссылка
 * выдаётся, вызова за ней нет). Два запроса подряд и сравнение двух ссылок
 * отвечают на вопрос «есть ли такая запись». Закрывается это не здесь:
 * несуществующему ключу нужна ссылка, устойчивая в пределах того же окна, а
 * значит — вывод ссылки ключом в шаге приложения. Это то же место, что и §Z3
 * **[открыто]**, и делается тем же решением владельца.
 *
 * ## Что держит это правило снаружи пакета
 *
 * Само правило — над значением: ни хранилища, ни канала, ни часов внутри. Но
 * работает оно только потому, что хранилище выполняет два условия, и оба
 * проверяются на живой базе (`db/test/int/auth-store.int.test.ts`):
 *
 * 1. `latestFor(accountId)` отдаёт самый свежий вызов записи **в любом
 *    состоянии**. Живой возвращается тому, кто попросил повторно; закрытый
 *    нужен ради своей отметки об отправке.
 * 2. Отметка об отправке двигается на **каждую** отправку, включая повторную
 *    (`0025`). Неподвижная отметка — не «правило не работает», а «правило
 *    работает неверно»: разница с ней только растёт, то есть окно открывается
 *    один раз и больше не закрывается никогда.
 *

 * ## Чего здесь нет
 *
 * **Ограничения по сети.** Тысяча ключей даёт тысячу отправок в окно, и против
 * этого нужен вариант А из §Z2 — счётчики на транспорте. Они требуют места под
 * состояние, которого здесь нет: своей таблицы или новой зависимости. Вариант
 * остаётся открытым.
 *
 * **Записи о придержанном запросе.** Отказа не произошло, и `session_denied`
 * тут был бы неправдой; своего ключа причины у «слишком часто» нет, а завести
 * его — это правка перечня, продублированного в `packages/audit` и в типе базы.
 * След при этом не теряется совсем: сколько вызовов выдано записи за час,
 * видно по самой таблице вызовов.
 */

/** Часы потока запросов. Одно число, и оно временное — см. константу ниже. */
export interface CodeRequestClock {
  /** Не чаще одной отправки на учётную запись за это время. */
  readonly resendWindow: DurationMs;
}

/**
 * ⚠ **ВРЕМЕННОЕ ЗНАЧЕНИЕ, НЕ РЕШЕНИЕ ВЛАДЕЛЬЦА.**
 *
 * Числа окна нет ни в одном документе проекта: §Z2 оставляет его владельцу —
 * сам вариант закрыт мной, число нет. Здесь стоит **минута**, и выбрана она по
 * трём соображениям, а не по привычке:
 *
 * - это тот интервал, который интерфейс может показать обратным отсчётом
 *   («отправить ещё раз через 0:47») — обещание, которое человек проверяет
 *   секундомером, поэтому оно обязано быть коротким и честным;
 * - минута короче любого разумного ожидания сообщения: человек, у которого SMS
 *   идёт дольше, всё равно не остаётся без входа — ссылка на живой вызов
 *   возвращается ему сразу, без отправки;
 * - на счёт за отправку она действует так: всплеск из ста запросов
 *   превращается в одну отправку, а десятиминутный срок кода — не более чем в
 *   десять.
 *
 * Чего минута **не** закрывает: поток по многим учётным записям сразу. Тысяча
 * ключей даёт тысячу отправок в окно, и против этого нужен вариант А
 * (ограничение по сети на транспорте) — он остаётся открытым.
 *
 * Вопрос — `DECISIONS-REVIEW.md` §Z2 **[открыто]**.
 */
export const PROVISIONAL_CODE_REQUEST_CLOCK: CodeRequestClock = Object.freeze({
  resendWindow: duration(60 * 1000),
});

/**
 * Что делать с запросом кода.
 *
 * Союз, а не запись с флагами: «отправить» без вызова и «записать» без нового
 * вызова — состояния, которых не бывает, и типу незачем их допускать. У
 * `withheld` вызова нет вовсе — отправить нечего, даже если очень захотеть.
 */
export type CodeRequestPlan =
  | {
      /** Живого вызова не было: заводится новый, код уходит в канал. */
      readonly outcome: 'issued';
      readonly reference: ChallengeId;
      readonly challenge: IdentityChallenge;
    }
  | {
      /** Тот же вызов и тот же код — второй раз в канал: окно вышло. */
      readonly outcome: 'resent';
      readonly reference: ChallengeId;
      readonly challenge: IdentityChallenge;
    }
  | {
      /** Ни записи, ни отправки. Ссылка при этом выдаётся — ответ один на все. */
      readonly outcome: 'withheld';
      readonly reference: ChallengeId;
      readonly challenge: null;
    };

export interface CodeRequestInput {
  readonly accountId: AccountId;
  /**
   * Самый свежий вызов учётной записи — **в любом состоянии**, а не только
   * живой. Закрытый нужен ради отметки об отправке: без неё «вызов закрыт»
   * читается как «отправлять можно», и пять неверных ответов открывают канал
   * заново.
   */
  readonly latest: IdentityChallenge | null;
  /** Идентификатор на случай нового вызова. Берётся всегда: см. `reference`. */
  readonly fresh: ChallengeId;
  readonly now: Instant;
}

/**
 * Решение по запросу кода. Ни хранилища, ни канала, ни часов внутри: всё
 * приходит значением, поэтому правило проверяется без сети и без базы.
 */
export function planCodeRequest(
  input: CodeRequestInput,
  clock: CodeRequestClock = PROVISIONAL_CODE_REQUEST_CLOCK,
  policy: IdentityCodePolicy = IDENTITY_CODE_POLICY,
): CodeRequestPlan {
  const latest = mine(input);
  const live = latest !== null && challengeStatus(latest, input.now) === 'pending' ? latest : null;
  const quiet = latest !== null && withinWindow(latest.deliveredAt, input.now, clock);

  if (live !== null) {
    // Тот же вызов возвращается в обоих исходах: повторный запрос не заводит
    // второго живого вызова, не сдвигает срок и не обнуляет счётчик попыток —
    // иначе «пришлите ещё раз» было бы способом получить шестую попытку.
    return quiet
      ? Object.freeze({ outcome: 'withheld', reference: live.challengeId, challenge: null })
      : Object.freeze({ outcome: 'resent', reference: live.challengeId, challenge: live });
  }

  if (quiet) {
    // Живого вызова нет, но отправка была только что. Ссылка выдаётся и ведёт в
    // пустоту — ровно как у несуществующей записи (`sign-in.ts`), потому что
    // ответ обязан быть один и тот же. Ждать при этом до конца срока кода не
    // приходится: закрытый вызов задерживает новый на окно, а не на срок.
    return Object.freeze({ outcome: 'withheld', reference: input.fresh, challenge: null });
  }

  const challenge = issueChallenge(
    { challengeId: input.fresh, accountId: input.accountId, issuedAt: input.now },
    policy,
  );
  return Object.freeze({ outcome: 'issued', reference: challenge.challengeId, challenge });
}

/**
 * Чужой вызов — не вызов этой записи.
 *
 * Проверка дешёвая и здесь не лишняя: `latest` приходит из хранилища по ключу
 * учётной записи, и ошибка в этом запросе означала бы, что человеку возвращают
 * ссылку на чужой вызов. Отказ в этом случае — завести свой, а не отдать чужой.
 */
function mine(input: CodeRequestInput): IdentityChallenge | null {
  if (input.latest === null) return null;
  return input.latest.accountId === input.accountId ? input.latest : null;
}

/**
 * Идёт ли окно молчания.
 *
 * `null` (не отправляли ни разу) окном не считается: отказавший канал не должен
 * запирать человека — иначе поломка на нашей стороне выглядит как ограничение.
 * Отметка из будущего (переведённые часы) считается окном: сомнение здесь
 * решается в пользу тишины, а не лишней отправки.
 */
function withinWindow(last: Instant | null, now: Instant, clock: CodeRequestClock): boolean {
  return last !== null && now - last < clock.resendWindow;
}
