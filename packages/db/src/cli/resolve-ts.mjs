/**
 * Разрешение относительных импортов **без расширения** для запуска команд
 * напрямую в node.
 *
 * ⚠ Это обход, а не решение, и место ему здесь только потому, что причина лежит
 * в чужих пакетах. `@sdelka/app`, `@sdelka/audit`, `@sdelka/ledger` и соседи
 * написаны с импортами вида `export * from './anchor'` — так их разрешает
 * сборщик приложения, но не node: в ESM расширение обязательно. Пока это так,
 * любая команда, дотягивающаяся до слоя приложения, падает при запуске с
 * `ERR_MODULE_NOT_FOUND`, и заметить это можно только в день, когда команда
 * понадобилась.
 *
 * Такой же хук стоит в `@sdelka/backup` (`src/cli/resolve-ts.mjs`) — по той же
 * причине и слово в слово. Общего места у них нет намеренно: `@sdelka/db` от
 * `@sdelka/backup` не зависит и зависеть не должен, а заводить пакет ради
 * двадцати строк обхода дороже, чем снять сам обход.
 *
 * Хук ничего не «угадывает»: он вступает в дело **только** после того, как
 * штатное разрешение уже отказало, и только для относительного пути, дописывая
 * ровно одно расширение. Импорт, который не разрешается и с ним, отдаёт
 * исходную ошибку — подмена одного отказа другим здесь была бы хуже отказа.
 *
 * Настоящее решение — расширения в исходниках этих пакетов. Оно за границей
 * этого пакета; после него хук снимается вместе с этим файлом.
 */
export async function resolve(specifier, context, nextResolve) {
  try {
    return await nextResolve(specifier, context);
  } catch (error) {
    if (!specifier.startsWith('.') || /\.[cm]?[jt]sx?$/u.test(specifier)) throw error;
    try {
      return await nextResolve(`${specifier}.ts`, context);
    } catch {
      throw error;
    }
  }
}
