/**
 * Роли и схема.
 *
 * Имена ролей — идентификаторы, а не секреты, и потому живут в коде: секрет —
 * это пароль и хост, они приходят строкой подключения из окружения
 * (`env.ts`, красная линия №12).
 *
 * **Роль приложения намеренно не владеет объектами.** Инвариант 21
 * (`FUNCTIONAL.md`) и `CORE.md` Ф11 требуют, чтобы права на изменение и удаление
 * журнала аудита отсутствовали у роли приложения и проверялись **грантами**. У
 * владельца объекта отобрать права нельзя: он в любой момент выдаст их себе
 * обратно, и `REVOKE` превращается в театр. Поэтому владелец — `sdelka_owner`,
 * приложение — `sdelka_app`, и второй не член первого.
 *
 * Обе роли заводятся **без права входа**: пароля у них нет ни в репозитории, ни
 * в миграции. Логин-роль создаёт оператор снаружи и включает её в нужную
 * групповую роль (`scripts/dev-db.sh` делает это для локального кластера).
 */
export const SCHEMA_NAME = 'sdelka';

/** Владелец всех объектов схемы. Под ним выполняются миграции. */
export const OWNER_ROLE = 'sdelka_owner';

/** Роль приложения. Не владелец, не суперпользователь, без прав на журналы. */
export const APP_ROLE = 'sdelka_app';

/** Таблица применённых миграций. */
export const MIGRATION_TABLE = `${SCHEMA_NAME}.schema_migration`;

/**
 * Ключ консультативной блокировки на время миграции. Произвольное, но
 * постоянное число: две параллельные миграции обязаны выстроиться в очередь, а
 * не наложиться друг на друга.
 */
export const MIGRATION_LOCK_KEY = 8_142_557_003_311_270n;
