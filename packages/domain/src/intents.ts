import type { DealPartiesAttestation } from '@sdelka/ledger';
import type { CurrencyCode, Money } from '@sdelka/money';
import type { FreezeReason, UnfreezeTarget } from './freeze';
import type { DurationMs, Instant } from './instant';
import type { FeeCeilingPolicy } from './tariff';

/**
 * Действия при входе и выходе (STATE-MACHINES.md §1.5) — описания намерений,
 * а не вызовы. Редьюсер их только возвращает: внешние вызовы идут через
 * исходящую очередь и никогда внутри транзакции (FUNCTIONAL.md инвариант 15).
 *
 * Операции с **двумя моментами** здесь и представлены двумя шаблонами, а не
 * одним (FUNCTIONAL.md §3.1). Возврат: отвязка от транша — это возврат денег в
 * свободную часть счёта покупателя, они всё ещё у нас и всё ещё его; уход с
 * номинального счёта на счёт-источник — отдельное событие и отдельный
 * межбанковский перевод, подтверждаемый банком. Раньше у возврата был один
 * шаблон, и каждая проекция сама выбирала, какой из двух моментов он значит:
 * домен записывал отвязку, приложение — внешний вывод. Тест на свойствах гонял
 * при этом не ту модель, которой пользовалось приложение.
 *
 * Списание оставлено одним шаблоном намеренно: его второй момент — «деньги
 * дошли на операционный счёт» — не переход транша, а факт банковской выписки.
 * Транш к этой секунде уже терминален, и автомату сказать о ней нечего.
 */
export type LedgerTemplate =
  /**
   * Зачисление на счёт клиента, и **только оно** (FUNCTIONAL.md §3.1: зачисление
   * и привязка к сделке — разные события, и сумма журнала равна нулю на каждом).
   *
   * Раньше этот шаблон означал разное в трёх проекциях: проекция домена делала
   * зачисление **и** запирание подряд, приложение — только зачисление и ждало
   * отдельного вызова, интерфейс запирал вообще на другом статусе. Момент
   * запирания разошёлся между проекциями, потому что автомат его не называл.
   */
  | 'funds_received'
  /**
   * Привязка к сделке: свободные деньги клиента запираются под транш
   * (FUNCTIONAL.md §3.1, четыре проводки).
   *
   * **[решение] Запирание — вход в `reserved`, а не в `collected`.** Документ
   * момент не задавал вовсе, и три проекции ответили по-разному. Верна третья:
   * STATE-MACHINES.md §6 определяет `collected` как «деньги на вашем счёте,
   * можете забрать», а `ROADMAP.md` И12.2 — «вывод доступен, пока средства не
   * зарезервированы». Запирание в `collected` делает оба обещания ложными:
   * забрать нельзя ничего, а экран говорит, что можно.
   */
  | 'lock_funds'
  /**
   * Расфиксация: резерв снят, деньги вернулись в свободную часть счёта того же
   * клиента (`reserved → collected` и `release_blocked → collected` по
   * `reserve_expired`).
   *
   * Симметричная половина запирания, и её не было ни у одной проекции: при
   * `reserve_expired` деньги в учёте оставались запертыми под траншем, который
   * в интерфейсе уже считал их свободными. `CABINETS.md` §3.2 блок 6 обещает
   * буквально «резерв будет снят автоматически и деньги останутся у вас».
   */
  | 'unlock_funds'
  /** Возврат, момент 1: отвязка от транша в свободную часть счёта покупателя. */
  | 'refund_unlock'
  /** Возврат, момент 2: деньги ушли с номинального счёта на счёт-источник. */
  | 'refund_external'
  /**
   * Списание, момент 1 (§3.1, случай Б): обязательство по траншу закрывается,
   * деньги уходят с номинального счёта в транзит и становятся долгом
   * невостребованных. Момент 2 — приход на операционный счёт — вне автомата.
   */
  | 'write_off';

export type Audience = 'buyer' | 'seller' | 'both' | 'operator';

export type Intent =
  | { readonly type: 'set_deadline'; readonly at: Instant }
  /**
   * Заморозка приостанавливает дедлайн, а не отменяет его (CORE.md Ф17).
   * Планировщик обязан снять таймер и запомнить остаток: у замороженного транша
   * момента срабатывания нет, а неистёкшая часть есть.
   */
  | { readonly type: 'suspend_deadline'; readonly remaining: DurationMs }
  | {
      readonly type: 'post_journal_entry';
      readonly template: LedgerTemplate;
      readonly dealId: string;
      readonly trancheId: string;
      /**
       * Владелец обязательства по этому траншу — ключ счёта плательщика.
       * После E12-1 счёт клиента в плане счетов адресуется владельцем
       * (`client:{клиент}:tranche:{сделка}:{транш}`), и без владельца намерение
       * невозможно спроецировать в проводку. Тип строковый: брендирование ключа
       * остаётся заботой учёта, домен ключ только переносит.
       */
      readonly clientKey: string;
      readonly amount: Money<CurrencyCode>;
    }
  /**
   * Расчёт в пользу получателя — **отдельное намерение, а не шаблон**.
   *
   * Причина в том, что расчёт единственный переносит обязательство от одного
   * лица к другому, и красная линия №1 держится ровно на этом переносе: пока
   * получателя называл параметр приложения, деньги покупателя могли осесть у
   * кого угодно, а тот законно запирал их под свою сделку. Учёт закрыл свою
   * половину — движение обязательства между владельцами он требует
   * подтверждать, — но подтверждение обязано прийти оттуда, где живёт знание о
   * составе сторон, то есть отсюда.
   *
   * Поэтому у расчёта нет варианта «без подтверждения»: поле обязательно по
   * типу, а значение его невозможно построить кодом (у `DealPartiesAttestation`
   * ambient-ключ). Приложение может только передать полученное намерение в
   * учёт — сочинить его или подставить другого получателя оно не может.
   *
   * Отсюда же и второе следствие: собрать проводку расчёта, не пройдя через
   * автомат транша, нельзя вовсе. «Просто выплатить» не существует как
   * операция (красная линия №5) не потому, что это проверяется, а потому, что
   * нечем.
   */
  | {
      readonly type: 'post_settlement_entry';
      readonly dealId: string;
      readonly trancheId: string;
      /** Плательщик: владелец запертой части, которая дебетуется. */
      readonly payerClientKey: string;
      /** Получатель: тот, кого назвал акт об условии, и никто другой. */
      readonly recipientClientKey: string;
      readonly amount: Money<CurrencyCode>;
      /**
       * Потолок удержания, действовавший для этого транша в момент решения
       * (`tariff.ts`, эпик E16; `CORE.md` Ф11).
       *
       * **[исправляет предыдущее] Едет политика, а не посчитанная сумма.**
       * Прежняя редакция клала сюда `maxWithholding` — наибольшее законное
       * удержание в тетри — и оговаривала, что это «утверждение, а не запрет»:
       * проекция расчёта поле не читала, и оговорка оказалась верной буквально.
       * Числу и нельзя было доехать до записи: учёт меряет удержание **долей**
       * от брутто (`fee-ceiling.ts`), поэтому сумма на входе записи ничего не
       * ограничивает, а перевод одного в другое стал бы местом, где предел
       * теряется. Поэтому в намерении едет ровно то значение, которым запрет и
       * пользуется, — политика (`FeeCeilingPolicy`, структурно `FeeCeiling`
       * учёта), и она доезжает до `trancheSettlement` без перевода.
       *
       * Само наибольшее удержание отсюда считается одной строкой —
       * `maxWithholding(amount, feeCeiling)`, — поэтому второй правды об одном
       * пределе в намерении нет.
       *
       * **Только сужает.** Действующим на записи считается строжайший из этой
       * политики и жёсткого предела учёта (`DEFAULT_FEE_CEILING`): объявление
       * не может разрешить больше, чем разрешает учёт.
       */
      readonly feeCeiling: FeeCeilingPolicy;
      /**
       * Подтверждение сторон для учёта. Выдаётся автоматом транша в момент
       * расчёта и только для той пары, которую записал акт; несёт ссылку на
       * пакет доказательств (красная линия №5).
       */
      readonly attestation: DealPartiesAttestation;
    }
  /** `messageKey` — ключ локализации. Текста для клиента в коде нет. */
  | { readonly type: 'notify'; readonly audience: Audience; readonly messageKey: string }
  | { readonly type: 'lock_beneficiary' }
  | { readonly type: 'unlock_beneficiary' }
  | { readonly type: 'build_payout_instruction'; readonly idempotencyKey: string }
  /**
   * Ссылка на пакет доказательств обязательна по типу: красная линия №5 —
   * выплата без неё невозможна, «просто выплатить» не существует как операция.
   */
  | {
      readonly type: 'enqueue_outbound_payout';
      readonly idempotencyKey: string;
      readonly evidenceBundleId: string;
    }
  /**
   * Поручение на возврат покупателю — **отдельное намерение, а не расчёт с
   * другим получателем.**
   *
   * Ссылки на пакет доказательств здесь нет, и это не послабление красной
   * линии №5, а её граница. №5 запрещает выплату **получателю** без
   * доказательств наступившего условия; возврат отдаёт покупателю его
   * собственные деньги, и доказывать для этого нечего — наоборот, требование
   * пакета сделало бы невозможным возврат по бездействию (красная линия №7) у
   * транша, до которого доказательства не дошли вовсе. Обязательным по типу
   * пакет остаётся ровно там, где он и был.
   *
   * Что охраняет эту ногу вместо №5: `g_source_account_known` на ребре
   * `refund_pending → refunding` (деньги идут на счёт-источник, а не на
   * назначенные кем-то реквизиты, красная линия №9) и `g_no_active_payout` там
   * же (поручение в полёте не бывает вторым, красная линия №8).
   *
   * Раньше намерения не было: вход в `refunding` не порождал ничего, у
   * возврата не было записи поручения, и ответ банка по нему приложению
   * некуда было положить.
   */
  | { readonly type: 'enqueue_outbound_refund'; readonly idempotencyKey: string }
  | { readonly type: 'enqueue_operator_task'; readonly priorityAmount: Money<CurrencyCode> }
  /**
   * Каскад сделка → транши (CORE.md Ф17). Без него комплаенс замораживает
   * сделку, а её транши продолжают идти к автовозврату по дедлайну — то есть
   * заморозка не делает ровно того, ради чего существует.
   */
  | {
      readonly type: 'freeze_tranches';
      readonly reason: FreezeReason;
      readonly frozenBy: string;
    }
  | {
      readonly type: 'unfreeze_tranches';
      readonly userIds: readonly string[];
      readonly resume: UnfreezeTarget;
    }
  | { readonly type: 'close_tranche' };

export type IntentType = Intent['type'];
