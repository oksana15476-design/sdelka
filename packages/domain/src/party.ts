/**
 * Ссылка на сторону сделки — FUNCTIONAL.md §2.1: **личность одна, роль —
 * свойство участия**.
 *
 * До этого значения у одного и того же человека в домене было два ключа,
 * лежавших в разных местах и ничем не связанных: `TrancheFacts.buyerPartyId`
 * (кто из сторон принял редакцию условия) и `TrancheContext.payerClientKey`
 * (чей счёт дебетуется проводкой). Между ними не стояло ни одной сверки, то
 * есть приложение могло назвать стороной одного, а деньги взять со счёта
 * другого — и ни один guard этого не видел. Ровно того же класса дефект
 * верификатор нашёл у получателя: свободный параметр вместо связи.
 *
 * Здесь оба представления одной личности лежат **в одном неизменяемом
 * значении**, и порознь их взять неоткуда: у `PartyRef` нет конструктора,
 * который брал бы только половину. Подставить чужой счёт можно теперь только
 * подставив чужую сторону целиком — а сторону сделки называет акт об условии и
 * сверяет комплаенс.
 *
 * Почему два поля, а не одно. `partyId` — ключ, которым сторона названа в
 * профилях, санкционном скрининге и журнале аудита. `accountKey` — форма того
 * же лица в плане счетов (`client:{клиент}:...`), и алфавит у неё другой:
 * двоеточие в учёте разделяет сегменты кода счёта. Свести их в один ключ
 * значит навязать одному из двух пакетов чужой алфавит; связать их в одном
 * значении — достаточно.
 */
export interface PartyRef {
  /** Ключ стороны: им сторона названа в профилях, скрининге и журнале аудита. */
  readonly partyId: string;
  /**
   * Ключ счёта клиента в учёте. Домен его не разбирает и не строит — только
   * переносит: брендирование ключа и его алфавит остаются заботой учёта.
   */
  readonly accountKey: string;
}

export function partyRefsEqual(left: PartyRef, right: PartyRef): boolean {
  return left.partyId === right.partyId && left.accountKey === right.accountKey;
}

/**
 * Пустая половина ссылки — это отсутствующая сторона, а не сторона с пустым
 * именем. Проверка в рантайме, а не только по типам: ссылка приходит из базы и
 * из внешнего интерфейса, а типы границу процесса не переживают.
 */
export function isPartyRefValid(ref: PartyRef): boolean {
  return ref.partyId.length > 0 && ref.accountKey.length > 0;
}

/** Одно и то же лицо по обе стороны сделки — FUNCTIONAL.md §2.1, отказ. */
export function isSameParty(left: PartyRef, right: PartyRef): boolean {
  return left.partyId === right.partyId || left.accountKey === right.accountKey;
}
