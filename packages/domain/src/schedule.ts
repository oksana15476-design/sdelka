import { type Instant, isPast } from './instant';
import type { ThawedTrancheStatus, TrancheState } from './tranche';
import type { TrancheEvent } from './tranche-events';

/**
 * Часы транша: **что порождает наступление срока**, а не что оно делает.
 *
 * Ребро `reserved → collected on reserve_expired` в таблице переходов есть с
 * самого начала (STATE-MACHINES.md §1.4). Чего не было — вызывающего:
 * `Deadline` лежал в состоянии, `isPast` был объявлен и **не вызывался нигде**,
 * а `DEFAULT_DEADLINE_POLICY` ставила дедлайн всем девяти остывшим статусам,
 * из которых `deadline_reached` обслуживает только три. Семь дедлайнов
 * ставились и никем не читались, и `CABINETS.md` §3.2 блок 6 обещал
 * автоматическое снятие резерва, которого некому было выполнить.
 *
 * **Правило здесь, тик за портом.** Функция чистая и тотальная: она читает
 * только статус и момент срабатывания, `now` приходит аргументом. Ни таймера,
 * ни списка, ни обращения к `Date` — «дай транши, у которых часы истекли»,
 * транзакция, повтор и пятнадцатиминутный интервал (FUNCTIONAL.md инвариант 7)
 * домену не принадлежат. Поэтому и проверяется она без сети и без часов, что и
 * есть доказательство, что планировщик остался портом (STATE-MACHINES.md §7).
 *
 * **Возвращается событие, а не состояние.** Планировщик обязан проходить ту же
 * дверь, что и человек: таблицу переходов, guard'ы и намерения. Функция,
 * возвращающая состояние, была бы вторым редьюсером и обошла бы их все — и
 * тогда `deadline_reached` у замороженного транша, который таблица отвергает,
 * прошёл бы мимо неё.
 */
export type DueTrancheEventType = 'deadline_reached' | 'reserve_expired';

/**
 * Что должны часы каждого остывшего статуса — STATE-MACHINES.md §5, таблица
 * «Проверка на тупики». Таблица **частичная намеренно**: дедлайн есть у всех
 * девяти статусов, а автоматический переход по нему — не у всех, и `null`
 * здесь несёт ровно столько же смысла, сколько имя события.
 *
 * `frozen` в таблице нет по типу: у замороженного состояния поля `deadline`
 * не существует вовсе, сравнивать нечего, и ветка невыразима — тот же приём,
 * которым CORE.md Ф17 выражает приостановку часов.
 */
export const DUE_TRANCHE_EVENTS: Readonly<
  Record<ThawedTrancheStatus, DueTrancheEventType | null>
> = Object.freeze({
  /**
   * **[открыто]** `pending` — расхождение документа с самим собой, найденное
   * этой таблицей.
   *
   * §5 обещает «`pending`, `collecting` → дедлайн → `refund_pending`», но в
   * таблице переходов §1.4 у `pending` ребра `deadline_reached` **нет**: из
   * него ведёт только `instructions_issued`. Часы не вправе сочинить ребро —
   * они лишь называют событие, и событие, которого таблица не примет, будет
   * отвергаться каждые пятнадцать минут вхолостую.
   *
   * `null` здесь безопасен по существу: §1.4.1 определяет `pending` как
   * «создан, денег нет», а красная линия №7 говорит о возврате **денег**.
   * Возвращать нечего, удерживать нечего, и тупика нет — за брошенным
   * `pending` приходит эскалация по возрасту (`isEscalated`,
   * `DEFAULT_ESCALATION_POLICY.pending`), то есть человек, а не автомат.
   *
   * Что делать с расхождением — вопрос владельцу: либо §5 правится под
   * таблицу, либо в таблицу добавляется ребро, и тогда появляется транш,
   * дошедший до `refunded`, ни разу не державший денег.
   */
  pending: null,

  // §5: «Дедлайн обязателен» — выход в возврат, красная линия №7 (состояние по
  // умолчанию при бездействии есть возврат покупателю, а не удержание).
  collecting: 'deadline_reached',
  collected: 'deadline_reached',

  /**
   * **`reserve_expired`, а не `deadline_reached`** — и это решение, продиктованное
   * документом, а не удобством.
   *
   * STATE-MACHINES.md §5 называет выход из `reserved` «отсечкой рабочего дня»,
   * но событие ему не даёт; `CABINETS.md` §3.2 блок 6 даёт дословно: «если
   * регистрация не завершится до 18:00 сегодня, резерв будет снят автоматически
   * **и деньги останутся у вас. Сделку можно будет провести заново**». Это и
   * есть `reserved → collected`: деньги возвращаются в свободную часть счёта,
   * сделка остаётся живой.
   *
   * `deadline_reached` увёл бы транш прямо в `refund_pending`, минуя обещанное
   * «провести заново», — то есть экран обещал бы одно, а автомат делал другое.
   * Строки `reserved → deadline_reached` в таблице переходов нет **намеренно**,
   * а не по недосмотру.
   */
  reserved: 'reserve_expired',

  /**
   * §5: «единственное состояние, выход из которого зависит от человека.
   * Поэтому эскалация по возрасту и алерт при превышении норматива». Часы
   * здесь поднимают дежурного (`isEscalated`), а не двигают деньги:
   * автоматический выход из `release_blocked` — это и есть тот дефект, ради
   * запрета которого состояние существует.
   */
  release_blocked: null,

  /**
   * Домен не вправе сочинить ответ банка. §2.2: «ни один адаптер не возвращает
   * `rejected` при сетевой ошибке» — отказ есть явный ответ провайдера, а не
   * отсутствие ответа, и ответ не наступает от того, что прошло время. Выход
   * отсюда гарантирует ежедневная сверка (§5), то есть внешний факт.
   */
  paying_out: null,
  refunding: null,

  /**
   * `refund_pending → refunding` идёт по `refund_initiated` — это **выпуск
   * поручения**, действие приложения с guard'ом `g_source_account_known`, а не
   * течение времени. Часы здесь тоже поднимают дежурного, а не выпускают
   * поручение за него.
   */
  refund_pending: null,

  /**
   * **[открыто]** Что должны часы `release_pending` — вопрос владельцу (О3).
   * §5 называет выход отсюда «задачей в очереди с эскалацией», то есть
   * возрастом, а не переходом. Ребро `release_pending → release_blocked` идёт
   * по `operator_blocked`, и событие несёт `reason: string` — свободную строку,
   * которую планировщику пришлось бы сочинить. Сочинённое основание блокировки
   * попадает в задачу оператора и в журнал аудита как настоящее; до ответа
   * владельца здесь `null`.
   */
  release_pending: null,
});

/**
 * Событие, которое наступление срока порождает у этого транша **сейчас**, или
 * `null`, если часы этого статуса не двигают деньги либо срок ещё не настал.
 *
 * `null` у замороженного и у терминального — структурно: поля `deadline` у них
 * нет, и до таблицы вызов не доходит.
 *
 * Одно состояние на вызов. `dueTrancheEvents(states, now)` здесь нет
 * намеренно: список траншей, у которых истекли часы, — это запрос к хранилищу,
 * то есть забота порта, а не домена.
 */
export function dueTrancheEvent(state: TrancheState, now: Instant): TrancheEvent | null {
  if (!('deadline' in state)) {
    return null;
  }
  if (!isPast(state.deadline, now)) {
    return null;
  }
  const type = DUE_TRANCHE_EVENTS[state.status];
  return type === null ? null : Object.freeze({ type });
}
