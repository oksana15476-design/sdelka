import type { PartyRef } from './party';

/**
 * **Участие** — сторона в конкретной сделке в конкретной роли.
 *
 * `FUNCTIONAL.md` §2.1: «личность одна, роль — свойство участия в сделке, а не
 * человека». До этого файла понятия участия в домене не было вовсе: сторона
 * лежала в фактах транша (`buyer`, `conditionAct.recipient`), а всё ролевое —
 * реквизиты выплаты — висело **на транше одним значением без ключа**. Из этого
 * следовало ровно то, что `ROADMAP.md` И13.1 запрещает: подтверждение
 * реквизитов, полученное по сделке А, приложение могло подать фактом по сделке
 * Б, и ни один guard этого не видел. Один раз прошедший проверку получал
 * подтверждённый канал вывода по любой будущей сделке — это не ослабление
 * контроля, а его отсутствие.
 *
 * Ролевые артефакты, которые висят на участии, а не на личности (§2.1):
 * **источник средств** — у того, кто платит, **реквизиты выплаты** — у того,
 * кто получает. Проверка личности и санкционный скрининг, наоборот, проходятся
 * один раз на личность и участию не принадлежат.
 *
 * **Гранулярность — сделка, не транш** (`dealId`, а не `dealId + trancheId`).
 * И13.1 говорит «подтверждение по одной сделке не переносится на другую», И13.2
 * — «процедура применяется к участию, где он получает; на вторую сделку
 * изменение не распространяется». Оба критерия — про сделку. Транши — это
 * график платежей по одному объекту с одним получателем, и требовать отдельного
 * тестового перевода на каждый транш рассрочки значит требовать его двенадцать
 * раз подряд на один и тот же счёт. Развилка «переносится ли подтверждение
 * между траншами одной сделки» вынесена владельцу — `DECISIONS-REVIEW.md`,
 * пометка **[открыто]**; здесь выбран менее строгий край, и он назван.
 */
export const PARTICIPATION_ROLES = ['buyer', 'recipient'] as const;

export type ParticipationRole = (typeof PARTICIPATION_ROLES)[number];

/**
 * Ключ участия. Класс, а не интерфейс, и **приватное поле** в нём — не
 * украшение: приватное поле делает тип номинальным, то есть значение этого типа
 * нельзя собрать ни литералом, ни спредом чужого значения. На ключе это ещё
 * дёшево, но на подтверждении реквизитов (`beneficiary.ts`) это единственное,
 * что превращает «не переносим» в «перенести не компилируется»: спред
 * `{ ...подтверждениеА, participation: ключБ }` перестаёт быть выражением типа
 * подтверждения. Брендирование ambient-символом, которым устроен
 * `DealPartiesAttestation` в учёте, здесь не годится — спред такой символ
 * копирует, и подмена одного поля проходит компиляцию (проверено).
 *
 * Конструктор наружу не выпущен: экспортируется **тип**, а не класс. Собрать
 * ключ можно только через `participationKey`, где он строится из ссылки на
 * сторону целиком, а не из голой строки.
 */
class ParticipationKeyValue {
  /** Номинальность типа. Значение неважно, важна недоступность поля снаружи. */
  readonly #nominal = 'sdelka.participation';

  readonly dealId: string;
  readonly partyId: string;
  readonly role: ParticipationRole;

  constructor(dealId: string, partyId: string, role: ParticipationRole) {
    this.dealId = dealId;
    this.partyId = partyId;
    this.role = role;
    Object.freeze(this);
  }

  /**
   * Приватное поле обязано быть **прочитано** хотя бы раз, иначе сборщик вправе
   * счесть его мёртвым кодом и выбросить — вместе с номинальностью типа.
   */
  toString(): string {
    return `${this.#nominal}:${this.dealId}:${this.partyId}:${this.role}`;
  }
}

export type ParticipationKey = ParticipationKeyValue;

/**
 * Ключ участия из ссылки на сторону.
 *
 * Сторона приходит `PartyRef`, а не строкой: половину личности (ключ профиля
 * без ключа счёта) взять неоткуда, и подставить чужого участника можно, только
 * подставив сторону целиком — тем же приёмом, что в `party.ts`.
 */
export function participationKey(
  dealId: string,
  party: PartyRef,
  role: ParticipationRole,
): ParticipationKey {
  return new ParticipationKeyValue(dealId, party.partyId, role);
}

/**
 * Пустая половина ключа — это отсутствующее участие, а не участие с пустым
 * именем. Проверка в рантайме по той же причине, что у `isPartyRefValid`:
 * значения приходят из базы и из внешнего интерфейса, а типы границу процесса
 * не переживают. Поднятый из снимка мир, у которого получателя ещё нет, кладёт
 * именно такой ключ — и всё, что на нём стоит, обязано отказать (`resume.ts`).
 */
export function isParticipationKeyValid(key: ParticipationKey): boolean {
  return key.dealId.length > 0 && key.partyId.length > 0;
}

/**
 * Равенство участий — по всем трём составляющим.
 *
 * Роль сравнивается наравне со сделкой и стороной: одно лицо бывает
 * покупателем и получателем в одной сделке невозможно (§2.1, отказ при
 * заведении), но в **разных** сделках — типовой случай, ради которого §2.1 и
 * написан, и склейка ролей вернула бы перенос подтверждения через роль.
 */
export function participationKeysEqual(left: ParticipationKey, right: ParticipationKey): boolean {
  return (
    left.dealId === right.dealId &&
    left.partyId === right.partyId &&
    left.role === right.role
  );
}
