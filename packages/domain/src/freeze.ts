/**
 * Заморозка транша — CORE.md Ф17, ROADMAP.md И9.2.
 *
 * Основание заморозки — **закрытый перечень**, а не строка. Причина та же, по
 * которой закрыт перечень типов условия (STATE-MACHINES.md §8): от основания
 * зависит, какие исходы разморозки вообще законны, а строковое основание
 * означает, что этот выбор делается в момент инцидента.
 */
export const FREEZE_REASONS = ['sanctions', 'compliance_review', 'dispute'] as const;

export type FreezeReason = (typeof FREEZE_REASONS)[number];

/**
 * Основания, по которым замораживает комплаенс. `dispute` сюда не входит: спор
 * поднимает сторона, а не комплаенс, и у него своё событие. Разведение по типу,
 * а не по значению поля, делает «спор с санкционным основанием» невыразимым.
 */
export type ComplianceFreezeReason = Exclude<FreezeReason, 'dispute'>;

export function isFreezeReason(value: string): value is FreezeReason {
  return (FREEZE_REASONS as readonly string[]).includes(value);
}

/**
 * Куда транш выходит из заморозки — явное поле решения двух людей (И9.2:
 * «целевое состояние есть явное поле, а не „вернуть как было“»), но перечень
 * закрытый.
 *
 * ⚠ Роадмап в И9.2 противоречит сам себе: один пункт требует «дедлайн
 * досчитывается на неистёкшую часть» (то есть возврат в тот же статус), соседний
 * — «целевое состояние есть явное поле». Противоречие снято так: поле явное, но
 * значений три, и остаток дедлайна применяется только у `suspended_from`. У
 * `refund_pending` и `release_blocked` часы чужие — остаток от них не наследуется,
 * дедлайн берётся из политики заново.
 *
 *  · `suspended_from` — вернуться в тот статус, из которого заморозили;
 *  · `refund_pending` — средства возвращаются (И9.2: санкционного основания
 *    не подтвердилось после внесения денег);
 *  · `release_blocked` — разбор человеком. Единственный допустимый исход, если
 *    заморозили `paying_out` или `refunding`: поручение уже ушло в банк, и
 *    возвращаться в состояние «поручение отправлено» значит выпустить его
 *    второй раз.
 */
export const UNFREEZE_TARGETS = ['suspended_from', 'refund_pending', 'release_blocked'] as const;

export type UnfreezeTarget = (typeof UNFREEZE_TARGETS)[number];
