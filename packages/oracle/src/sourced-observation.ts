import { type CapturedRawSource, AuditError, AuditErrorCode } from '@sdelka/audit';
import type { ReleaseObservation } from '@sdelka/domain';

/**
 * Наблюдение вместе с записанным сырым ответом источника.
 *
 * **Зачем тип, если отпечаток и так обязателен в `ReleaseObservation`.**
 * Обязателен там был не ответ, а строка: `rawSourceDigest` проверялся только на
 * форму (64 hex), и наблюдение с отпечатком, которому не соответствует ни один
 * полученный ответ, проходило все guard'ы. `verifyRawSource` при этом не
 * вызывался нигде, кроме собственного unit-теста, — то есть требование Ф11
 * («разобранные поля без исходника суд не убедит») держалось на дисциплине
 * вызывающего. Дисциплина забывается на третьем адаптере; тип — нет.
 *
 * `CapturedRawSource` из `@sdelka/audit` построить, не предъявив байты,
 * нечем. Поэтому событие `extract_received` теперь **непостроимо** без ответа
 * источника, а не «проверяемо на наличие отпечатка».
 *
 * **Подтип наблюдения, а не обёртка над ним.** Всё, что читает
 * `ReleaseObservation` — guard'ы транша, `observationSatisfies`, факты транша,
 * — читает и это значение без единой правки. Оборачивание потребовало бы
 * распаковки в каждой точке чтения, и первая же забытая распаковка вернула бы
 * дыру обратно.
 *
 * **Почему пакет оракула зависит от `@sdelka/audit`, а домен — нет.** Домен
 * чист намеренно: он про правила, а не про доказательства. Оракул — ровно та
 * граница, где ответ источника превращается в наблюдение, и держать здесь
 * доказательство нечем, кроме типа из пакета журнала.
 */
export interface SourcedObservation extends ReleaseObservation {
  readonly rawSource: CapturedRawSource;
}

/**
 * Свести наблюдение с ответом, из которого оно разобрано.
 *
 * Отказ — исключение, а не `Rejection`: наблюдение, разобранное из одного
 * ответа и предъявленное с другим, — это ошибка сборки, а не решение автомата,
 * и продолжать с таким значением нельзя ни в одном сценарии. Код ошибки берётся
 * из `@sdelka/audit`: расхождение отпечатка с ответом — это его предмет, и
 * второй ключ на то же самое означал бы два разных сообщения дежурному об одном
 * событии.
 */
export function sourcedObservation(
  observation: ReleaseObservation,
  rawSource: CapturedRawSource,
): SourcedObservation {
  if (observation.rawSourceDigest !== rawSource.digest) {
    // Значения в детали не кладём (дисциплина `compliance/src/pii.ts`):
    // отпечаток непрозрачен, но за ним стоит документ, и привычка класть его
    // в лог однажды положит туда соседнее поле.
    throw new AuditError(AuditErrorCode.rawSourceNotAttested, { reason: 'observation' });
  }
  return Object.freeze({ ...observation, rawSource });
}
