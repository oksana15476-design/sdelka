import { type Rational, rational } from '@sdelka/money';
import { PricingError, PricingErrorCode } from './errors';

/**
 * Единица, в которой хранится **любая доля** этого пакета: ставка тарифа и
 * наценка к курсу.
 *
 * **Целое число базисных пунктов над объявленным знаменателем.** Хранится
 * числитель (`rateBp`), знаменатель — константа `RATE_SCALE_BP`; в арифметику
 * величина уходит точной дробью `Rational` (`rational(bp, 10 000n)`), которую
 * `applyRational` считает целыми `bigint`. Ни одной операции с плавающей точкой
 * на пути от настройки до суммы (красная линия №4).
 *
 * **Почему базисные пункты, а не миллионные доли.** Обе формы целочисленны и
 * обе закрывают красную линию №4 одинаково; выбор между ними — это выбор
 * **единицы**, а двух единиц одной величины в проекте быть не должно. Базисный
 * пункт в проекте уже установлен и не мной:
 *
 *  · наценка к курсу считается формулой `client = reference · (10000 − markupBp)
 *    / 10000` (`FX.md` §7.2), то есть знаменатель 10 000 записан в документе;
 *  · допуск по сумме — `shareBp`, отвергается вне `0…10 000`
 *    (`packages/intake/src/tolerance.ts`);
 *  · порог сноса котировки, вес признака, раскрываемая наценка —
 *    `driftThresholdBp`, `valueBp`, `disclosedMarkupBp`;
 *  · экран владельца показывает ставку в базисных пунктах
 *    (`apps/web/src/fixtures/owner.ts`, `bpOf`).
 *
 * Ввести здесь миллионные значило бы завести вторую единицу доли и место, где
 * она переводится в первую, — а переведённая от руки величина расходится молча.
 *
 * ⚠ **Цена выбора названа вслух.** Шаг ставки — 0,01 %; на сумме 213 495 ₾ это
 * 21 ₾ на сделке. Ставку 0,4998 % из примера проводок (`FUNCTIONAL.md` §3.3)
 * в базисных пунктах выразить нельзя — но это и не ставка, а результат
 * округления комиссии 1 067 из 213 495; ставкой там служит 0,5 % = 50 б.п.
 * Если владельцу нужен шаг мельче — это **его** решение, и стоит оно правки
 * одной константы `RATE_SCALE_BP` вместе с границами: величина хранится
 * числителем, а знаменатель здесь один на пакет. Вопрос вынесен в
 * `DECISIONS-REVIEW.md` §J1 с пометкой **[открыто]**.
 */
export const RATE_SCALE_BP = 10_000n;

/** Тот же знаменатель числом — для границ, которые сравниваются с `number`. */
export const RATE_SCALE_BP_NUMBER = 10_000;

/**
 * Доля целым числом базисных пунктов.
 *
 * Проверяется **и** целочисленность, **и** диапазон, и это не педантизм:
 * величина приезжает из формы владельца и из базы, где `50.0000000001` —
 * обычный результат сериализации числа с плавающей точкой. Такая ставка
 * прошла бы `rational` (числитель стал бы дробным `bigint`… точнее, `BigInt`
 * бросил бы `RangeError` без кода и без поля) и умерла бы там, где разобрать её
 * нечем.
 */
export function assertBasisPoints(value: number, field: string): number {
  if (!Number.isInteger(value)) {
    throw new PricingError(PricingErrorCode.rateNotInteger, { field, value: String(value) });
  }
  if (value < 0 || value > RATE_SCALE_BP_NUMBER) {
    throw new PricingError(PricingErrorCode.rateOutOfRange, { field, value: String(value) });
  }
  return value;
}

/** Доля как точная дробь. Единственный переход «базисные пункты → арифметика». */
export function shareOf(basisPoints: number): Rational {
  return rational(BigInt(basisPoints), RATE_SCALE_BP);
}

/**
 * Дробь обратно в базисные пункты — **только для показа и сверки**, и с
 * усечением.
 *
 * Обратного перевода в расчёте нет ни одного: доля, посчитанная из дроби,
 * теряет разряды, и вернуть её в арифметику значило бы считать по округлённой
 * ставке. Отсюда и имя: `…ForDisplay`.
 */
export function basisPointsForDisplay(value: Rational): number {
  return Number((value.numerator * RATE_SCALE_BP) / value.denominator);
}
