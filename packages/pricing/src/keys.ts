/**
 * Отказы тарификации — **значения**, а не исключения: каждый приходится на
 * живой транш, и вызывающий обязан его разобрать (та же граница, что у
 * `SETTINGS_REFUSAL_KEYS`).
 */
export const PRICING_REFUSAL_KEYS = {
  /**
   * Комиссия, которую по этому плану несёт получатель, не помещается в сумму
   * сделки: минимум тарифа больше самой сделки.
   *
   * Отказ, а не усечение комиссии до суммы: усечение оставило бы продавцу ноль
   * и выглядело бы законным расчётом. Мелкая сделка, которую тариф не
   * обслуживает, — задача владельцу, а не молча съеденная сумма.
   */
  feeExceedsPrincipal: 'pricing.quote.fee_exceeds_principal',
  /**
   * Удержание по этому плану выходит за потолок удержания той же версии.
   *
   * Ловится **до** сбора проводок. Второй, необходимый рубеж стоит в записи
   * расчёта (`@sdelka/ledger`, `assertSettlementCeiling`) и считается из самих
   * проводок — здесь только ранний и внятный отказ.
   */
  feeAboveCeiling: 'pricing.quote.fee_above_ceiling',
  /**
   * Действующий план объявлен в другой валюте, чем сделка.
   *
   * Отказ закрытый, а не пересчёт фикса по курсу: курс — внешний факт, а
   * объявленная величина не может ездить вместе с рынком между инструкцией и
   * платежом. Та же форма, что у допуска в приёме
   * (`toleranceCurrencyNotDeclared`, `INTAKE.md` §3.2). Цена строгости названа:
   * владелец обязан объявить план в каждой валюте сделки, иначе тарификация
   * встанет задачей — а не посчитается по чужой валюте молча.
   */
  planCurrencyNotDeclared: 'pricing.quote.plan_currency_not_declared',
  /** Наценки по этой паре валют действующая версия расписания не объявляет. */
  markupPairNotDeclared: 'pricing.markup.pair_not_declared',
} as const;

export type PricingRefusalKey =
  (typeof PRICING_REFUSAL_KEYS)[keyof typeof PRICING_REFUSAL_KEYS];

