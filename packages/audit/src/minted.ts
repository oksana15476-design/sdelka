import { createHash } from 'node:crypto';
import { AuditError, AuditErrorCode } from './errors';

/**
 * Собственные детерминированные ключи: чем они доказываются журналу.
 *
 * ## Зачем это вообще понадобилось
 *
 * `values.ts` держит правило `digit_run`: значение с девятью и более цифрами
 * подряд считается сырым идентификатором человека — паспорт, личный номер,
 * телефон, счёт — и в вечный журнал не пускается. Правило грубое намеренно и
 * ослаблению не подлежит: журнал не редактируется (красная линия №11), и
 * персональные данные, попавшие в него открытым текстом, оттуда уже не убрать.
 *
 * Но под то же правило подпадает **наш собственный** ключ идемпотентности.
 * Он — UUID версии 5 (`domain/src/ids.ts`), то есть отформатированный отпечаток
 * SHA-1 от пространства имён и имени. Последняя группа канонической записи —
 * двенадцать шестнадцатеричных знаков, и девять из них подряд оказываются
 * цифрами примерно у каждого тридцать второго ключа. Замер: 200 000 ключей
 * `payoutIdempotencyKey('tranche-N')` — 6 233 попадания, **3,1 %**
 * [установлено]. Следствие: запись `payout_ordered` с таким ключом не
 * собиралась, и выплата не попадала в вечный журнал. Тестами это не ловилось,
 * потому что зависело от имени транша.
 *
 * ## Где проходит граница
 *
 * Различать надо не по форме, а по происхождению:
 *
 * - **наше** — значение, порождённое нами по известному правилу из известного
 *   входа. Оно не является идентификатором человека ни в каком смысле: это
 *   образ отпечатка, и восстановить по нему что-либо о человеке нельзя;
 * - **чужое** — значение, пришедшее от человека или из внешнего источника. Оно
 *   проверяется ровно как раньше, без единого послабления.
 *
 * Форма этого различия выразить не может: любую строку снаружи можно подать в
 * любом виде. Поэтому «своё» здесь **доказывается пересчётом**: заявка несёт
 * схему и вход, а `assertNoRawIdentifiers` пересчитывает по ним значение и
 * сверяет. Отсюда главное свойство: **объявить своим произвольную строку
 * нельзя**. Функция `auditMinted` значение не принимает — она его вычисляет; а
 * чтобы провести мимо правила паспортный номер, пришлось бы найти прообраз,
 * дающий этот номер образом SHA-1. Это не запрет по соглашению, а невозможность
 * по построению.
 *
 * ## Почему схемы продублированы здесь, а не взяты из `@sdelka/domain`
 *
 * По той же причине, что `AUDIT_ROLES` дублируют роли доступа: пакет аудита не
 * зависит ни от кого — журнал обязан пережить переделку домена. Молчаливым
 * расхождение не является: сверку ведёт `packages/e2e/test/minted-keys.test.ts`,
 * он видит оба пакета сразу, и разъехавшееся пространство имён роняет его.
 *
 * ## Чего здесь нет
 *
 * Заявка о чеканке **не хранится в записи**. Это пропуск на входе, а не поле
 * журнала: запись остаётся ровно той, какой была до этой правки — те же поля,
 * тот же канонический вид, тот же хеш. Иначе правка меняла бы прочтение уже
 * записанного, а это запрещено красной линией №11.
 */

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/u;

function uuidToBytes(uuid: string): Uint8Array {
  const hex = uuid.replace(/-/gu, '');
  const bytes = new Uint8Array(16);
  for (let index = 0; index < 16; index += 1) {
    bytes[index] = Number.parseInt(hex.slice(index * 2, index * 2 + 2), 16);
  }
  return bytes;
}

/**
 * UUID версии 5 (RFC 4122): SHA-1 от пространства имён и имени.
 *
 * Копия `domain/src/ids.ts` — двадцать строк, за которые пакет аудита не берёт
 * зависимость. Расхождение ловит сверка в `@sdelka/e2e`.
 *
 * Полубайты версии и варианта проставляются **по шестнадцатеричной записи**, а
 * не по байтам: срез строки всегда определён, и ветви «такого байта нет» —
 * недостижимой по построению, но обязательной при `noUncheckedIndexedAccess` —
 * здесь не возникает вовсе. Результат тот же до знака, и это проверено сверкой
 * с `@sdelka/domain`.
 */
function uuid5(namespace: string, name: string): string {
  const hash = createHash('sha1');
  hash.update(uuidToBytes(namespace));
  hash.update(new TextEncoder().encode(name));
  const hex = hash.digest('hex');
  const variant = ((Number.parseInt(hex.slice(16, 17), 16) & 0x3) | 0x8).toString(16);
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    `5${hex.slice(13, 16)}`,
    `${variant}${hex.slice(17, 20)}`,
    hex.slice(20, 32),
  ].join('-');
}

/**
 * Перечень схем чеканки — **закрытый**, и это его главное свойство.
 *
 * Новая схема появляется правкой этого файла и ревью, а не вызовом из
 * приложения. Реестра, в который можно что-то доложить в рантайме, здесь нет
 * намеренно: он и был бы той самой дверью «объявить своим что угодно», ради
 * закрытия которой всё это написано.
 *
 * ## Почему пространство имён здесь константа, а не вывод
 *
 * В `domain/src/ids.ts` оно выводится из адреса-имени и «не является магической
 * константой» — там это верно и оставлено как есть. Здесь адрес-имя написать
 * нельзя: `ports.test.ts` перебором файлов проверяет, что в пакете аудита нет
 * ни сети, ни обращений к окружению, и ловит он это по тексту — любое
 * упоминание адреса ронял бы проверку. Обходить её склейкой строки значило бы
 * сломать сторожа ради удобства.
 *
 * Поэтому здесь стоит **зеркало** — то же значение, что вывел домен, — а от
 * магической константы его отличает то, чем отличаются все зеркала этого пакета
 * (`AUDIT_ROLES`, `AUDIT_PRIMARY_METHODS`): сверка. `packages/e2e` видит оба
 * пакета сразу и сравнивает не только пространства имён, но и сами ключи на
 * общих входах. Разъехавшееся значение роняет её.
 */
export const MINT_SCHEMES = {
  /** `domain/src/ids.ts`, `PAYOUT_NAMESPACE`: ключ расчёта получателю. */
  payout_idempotency: 'ede3429d-450e-5390-ba3b-bf680b733b27',
  /** `domain/src/ids.ts`, `REFUND_NAMESPACE`: ключ возврата покупателю. */
  refund_idempotency: '7a48b364-df42-5a48-bcbb-1c1929943b1b',
  /** `domain/src/ids.ts`, `WITHDRAWAL_NAMESPACE`: ключ вывода со счёта клиента. */
  withdrawal_idempotency: '285085fc-ffb8-5600-9ad1-3d5c1235c9b5',
  /**
   * `domain/src/ids.ts`, `DEAL_APPLICATION_NAMESPACE`: ключ заявки на сделку.
   *
   * Схема заведена не ради ровности перечня. Номер заявки — тот же UUID5, и под
   * правило `digit_run` он подпадает с той же частотой, что ключ выплаты
   * (замер: 3,1 %). Без доказательства чеканки запись о подаче примерно каждой
   * тридцать второй заявки не собиралась бы вовсе — то есть заявка была бы
   * принята, а вечный журнал о ней бы молчал. Ровно тот дефект, который уже был
   * найден на выплате, и чинится он тем же способом: пересчётом из схемы и
   * входа, а не послаблением правила.
   */
  deal_application_idempotency: '41daa5ea-a04b-5be6-8a79-b3483ffed308',
} as const;

export type MintScheme = keyof typeof MINT_SCHEMES;

export const MINT_SCHEME_IDS = Object.freeze(Object.keys(MINT_SCHEMES) as readonly MintScheme[]);

export function isMintScheme(value: unknown): value is MintScheme {
  return typeof value === 'string' && Object.hasOwn(MINT_SCHEMES, value);
}

/** Пространство имён схемы. Совпадение с `@sdelka/domain` проверяется сверкой. */
export function mintNamespace(scheme: MintScheme): string {
  if (!isMintScheme(scheme)) {
    throw new AuditError(AuditErrorCode.mintSchemeUnknown);
  }
  return MINT_SCHEMES[scheme];
}

/**
 * Заявка о чеканке: схема, вход и полученное из них значение.
 *
 * `value` в конструктор **не передаётся** — он вычисляется. Поле существует
 * только затем, чтобы проверяющий не пересчитывал заявку дважды и чтобы
 * заявка, приехавшая разобранным `JSON` из чужого процесса, была отвергаема:
 * `mintIsAuthentic` пересчитывает и сверяет.
 */
export interface AuditMinted {
  readonly kind: 'minted';
  readonly scheme: MintScheme;
  /**
   * Известный вход: номер транша, номер заявки на вывод. Сам он в запись отсюда
   * не попадает — заявка не хранится, — поэтому персональных данных этим путём
   * в журнал не заносится ни при каком входе.
   */
  readonly source: string;
  /** Вычисленное значение. Совпадает с тем, что чеканит `@sdelka/domain`. */
  readonly value: string;
}

/**
 * Отчеканить значение по схеме и входу.
 *
 * Значение аргументом не принимается **никогда**: в этом весь смысл. Подать
 * сюда паспортный номер можно только входом — и тогда наружу выйдет UUID, а не
 * паспортный номер.
 */
export function auditMinted(scheme: MintScheme, source: string): AuditMinted {
  return Object.freeze({
    kind: 'minted' as const,
    scheme,
    source,
    value: uuid5(mintNamespace(scheme), source),
  });
}

export function isAuditMinted(value: unknown): value is AuditMinted {
  if (typeof value !== 'object' || value === null) return false;
  const claim = value as { kind?: unknown; scheme?: unknown; source?: unknown; value?: unknown };
  return (
    claim.kind === 'minted' &&
    isMintScheme(claim.scheme) &&
    typeof claim.source === 'string' &&
    typeof claim.value === 'string'
  );
}

/**
 * Пересчёт заявки — единственное, что делает её доказательством.
 *
 * Без него `AuditMinted` был бы просто объектом с полем «поверьте, это наше»:
 * приведением типа такой объект собирается из чего угодно. С ним подделка
 * требует прообраза SHA-1, дающего нужный образ.
 */
export function mintIsAuthentic(value: unknown): value is AuditMinted {
  if (!isAuditMinted(value)) return false;
  if (!UUID_PATTERN.test(value.value)) return false;
  return uuid5(MINT_SCHEMES[value.scheme], value.source) === value.value;
}
