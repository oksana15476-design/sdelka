import type { Journal, JournalEntry } from '../../src/index';

/**
 * Журнал, собранный в обход `appendEntry`.
 *
 * Тот же случай, что и `uncheckedEntry`, только этажом выше. `appendEntry`
 * держит правила, которым нужна история: одно начисление на транш, один обмен
 * на ключ конверсии, одно довнесение на признание. Собрать нарушающую их
 * последовательность через `appendEntry` нельзя — она отвергается.
 *
 * Второй контур — проверка инвариантов — обязан видеть такое состояние всё
 * равно: журнал приходит из базы, в том числе с записями, сделанными до
 * появления проверки. Именно так двойное начисление и живёт в уже записанных
 * журналах, и именно про них вопрос «а видно ли его вообще».
 */
export function unguardedJournal(entries: readonly JournalEntry[]): Journal {
  return Object.freeze({ entries: Object.freeze([...entries]) });
}
