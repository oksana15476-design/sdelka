import type { Session } from '@sdelka/auth';
import { cookies } from 'next/headers';
import { deliveryMode } from './auth-config';

/**
 * Идентификатор сессии в браузере — **только в куке, и только в такой**.
 *
 * Четыре свойства, и каждое закрывает свой способ угона:
 *
 * 1. **`httpOnly`.** Скрипт страницы куку не читает. Без этого любая
 *    внедрённая строка — и любая сторонняя библиотека — уносит сессию целиком,
 *    и уносит молча.
 * 2. **`secure`.** Кука не уходит по незащищённому соединению. В разработке
 *    признак снят: локальный сервер работает по `http`, и кука с `Secure` там
 *    просто не ставится — вход выглядел бы сломанным без единой ошибки.
 *    Решает это **объявленный режим**, а не догадка о хосте.
 * 3. **`sameSite: 'strict'`.** Кука не отправляется ни по одному переходу с
 *    чужого сайта. `lax` хватило бы против межсайтовой отправки формы (она
 *    идёт `POST`), но не против сценария, ради которого здесь строгость:
 *    ссылка из письма, ведущая на наш домен с параметрами злоумышленника, при
 *    `lax` открывается **уже авторизованной**. Цена названа: переход по
 *    внешней ссылке показывает неавторизованный экран, и человеку надо нажать
 *    ссылку внутри сайта ещё раз.
 * 4. **Срок куки равен сроку сессии.** Кука, живущая дольше сессии, — это
 *    предъявление мёртвого идентификатора на каждом запросе; кука, живущая
 *    меньше, — выход без записи об отзыве.
 *
 * Чего в куке нет: ни роли, ни имени, ни срока, ни подписи. Только
 * идентификатор — всё остальное лежит в базе и читается по нему. Подписанная
 * кука с полезной нагрузкой — это состояние, которое нельзя отозвать: красная
 * линия отзыва (`signOut`) держится тем, что состояние живёт на сервере.
 */
export const SESSION_COOKIE = 'sdelka_session';

export async function writeSessionCookie(session: Session): Promise<void> {
  const jar = await cookies();
  jar.set({
    name: SESSION_COOKIE,
    value: session.sessionId,
    httpOnly: true,
    secure: deliveryMode() === 'production',
    sameSite: 'strict',
    path: '/',
    expires: new Date(session.expiresAt),
  });
}

/**
 * Снятие куки.
 *
 * Ставится пустое значение с нулевым сроком, а не только `delete`: браузер,
 * получивший `Set-Cookie` без совпадающих `path` и признаков, куку не удаляет,
 * и «выход» оставляет идентификатор в браузере. Отзыв в базе от этого не
 * зависит — он уже произошёл, — но предъявляемый мёртвый идентификатор портит
 * журнал доступа.
 */
export async function clearSessionCookie(): Promise<void> {
  const jar = await cookies();
  jar.set({
    name: SESSION_COOKIE,
    value: '',
    httpOnly: true,
    secure: deliveryMode() === 'production',
    sameSite: 'strict',
    path: '/',
    maxAge: 0,
  });
}

/** Идентификатор сессии из куки. `null` — куки нет либо она пуста. */
export async function sessionCookieValue(): Promise<string | null> {
  const value = (await cookies()).get(SESSION_COOKIE)?.value ?? '';
  return value.length === 0 ? null : value;
}
