/**
 * Состояние здоровья приложения — **чистая часть**, без сети и без базы.
 *
 * «Процесс запустился» проверкой здоровья не является: процесс Next поднимается
 * и отвечает на запросы, не имея ни строки подключения, ни накаченной схемы, —
 * и снаружи это выглядит здоровьем ровно до первой денежной операции. Поэтому
 * ответ здесь собирается из трёх: жив ли процесс (сам факт ответа), готова ли
 * база (`db`) и настроен ли вход (`auth`).
 *
 * Вход попал сюда по той же причине, по которой попала база. Приложение с
 * незаданным режимом канала доставки кода или с боевым режимом без боевого
 * адаптера поднимается и отвечает на запросы — и не пускает **никого**, а в
 * худшем случае пускает, печатая одноразовый код в журнал процесса. Ни то ни
 * другое не здоровье, и узнать об этом обязан оркестратор, а не первый клиент.
 *
 * Тела ответа не видит клиент — его читает дежурный и оркестратор, поэтому
 * здесь **технические ключи**, а не пользовательский текст: локализовать
 * проверку здоровья не нужно и нельзя (CLAUDE.md, «Три языка»).
 *
 * Значений окружения в ответе нет и быть не может (красная линия №12): ни
 * строки подключения, ни хоста, ни имени роли. Только род отказа и, если он
 * известен, его код.
 */

/** Род состояния базы. Разбор по роду, а не «да/нет»: чинятся они по-разному. */
export type DbState =
  /** База ответила, схема накачена. `schema` — последняя применённая версия. */
  | { readonly kind: 'ready'; readonly schema: string }
  /** База ответила, но таблицы учёта миграций нет: накат не выполнялся. */
  | { readonly kind: 'unmigrated' }
  /** До базы не добрались: порт закрыт, имя не разрешилось, ответа нет. */
  | { readonly kind: 'unreachable' }
  /** Строка подключения не задана вовсе — ворота старта обошли. */
  | { readonly kind: 'unconfigured' }
  /** База ответила отказом: неверный пароль, нет базы, нет записи в `pg_hba`. */
  | { readonly kind: 'error'; readonly code: string };

/**
 * Настройка входа. Два состояния, а не «да/нет с текстом»: род отказа несёт
 * технический ключ (`web.auth.*`), и он же годится дежурному в отчёт.
 */
export type AuthConfigState =
  | { readonly kind: 'ready' }
  | { readonly kind: 'misconfigured'; readonly code: string };

export type HealthBody = {
  readonly status: 'ok' | 'fail';
  readonly db: DbState['kind'];
  readonly schema?: string;
  readonly code?: string;
  /**
   * Ключ отказа настройки входа. Поля **нет вовсе**, когда вход настроен:
   * молчание здесь — это утверждение, а не пропуск, и старые потребители ответа
   * от появления поля не ломаются.
   */
  readonly auth?: string;
};

export type HealthReport = {
  /** 200 — здоров; 503 — не готов обслуживать. Никаких «200 с полем fail». */
  readonly status: 200 | 503;
  readonly body: HealthBody;
};

/**
 * Код отказа, пропущенный через фильтр.
 *
 * Наружу уходит только то, что заведомо не содержит ни пароля, ни адреса:
 * наши технические ключи (`db.connect.timeout`) и SQLSTATE Postgres (`28P01`).
 * Всё остальное — включая текст сообщения драйвера, в который версия за версией
 * попадает то хост, то пользователь, — сворачивается в одно слово.
 */
const SAFE_CODE = /^[a-z][a-z0-9_.]{0,63}$|^[0-9A-Z]{5}$/u;

export const UNKNOWN_CODE = 'unknown';

export function safeCode(code: unknown): string {
  return typeof code === 'string' && SAFE_CODE.test(code) ? code : UNKNOWN_CODE;
}

/**
 * Ответ проверки здоровья по состоянию базы.
 *
 * Здоровье = процесс отвечает **и** база готова. Ненакаченная база — не
 * здоровье: приложение, поднятое раньше наката, обязано отвечать «не готово»,
 * иначе балансировщик пустит на него нагрузку (`db/src/schema-version.ts`
 * объясняет, чем это кончается).
 */
export function healthReport(
  db: DbState,
  auth: AuthConfigState = { kind: 'ready' },
): HealthReport {
  // Отказы не заменяют друг друга: база и вход чинятся по-разному, и дежурному
  // нужны оба рода сразу, а не первый найденный.
  const fault = auth.kind === 'misconfigured' ? { auth: auth.code } : {};
  if (db.kind === 'ready') {
    return auth.kind === 'ready'
      ? { status: 200, body: { status: 'ok', db: 'ready', schema: db.schema } }
      : { status: 503, body: { status: 'fail', db: 'ready', schema: db.schema, ...fault } };
  }
  if (db.kind === 'error') {
    return { status: 503, body: { status: 'fail', db: 'error', code: db.code, ...fault } };
  }
  return { status: 503, body: { status: 'fail', db: db.kind, ...fault } };
}
