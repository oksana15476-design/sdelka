import { coverage } from '@sdelka/ledger';
import { worldJournal } from '@/fixtures/store';

/**
 * Принимаем ли мы сейчас заявки с публичных страниц.
 *
 * ## Почему это состояние, а не текст
 *
 * Критерий приёмки ПЛ12 (`LANDING.md` §9) требует, чтобы «сейчас новые заявки
 * не принимаем» **не правилось руками в словаре**. Причина не в удобстве:
 * покрытие клиентских средств на конец банковского дня равно единице, и
 * отклонение останавливает приём новых сделок **автоматически** (красная линия
 * №3, Ф17). Остановка, которую нужно не забыть отразить на сайте, — это форма,
 * продолжающая собирать заявки, на которые никто не ответит.
 *
 * Поэтому положение читается из того же места, что и баннер консоли: из
 * покрытия по журналу (`ops/page.tsx`, `ops.coverage`). Разойтись эти два
 * экрана не могут по построению — источник один.
 *
 * ## Чего здесь нет
 *
 * Ручного переключателя «закрыть приём» нет: он был бы вторым источником правды
 * рядом с покрытием. Когда появится настоящий стоп-кран с собственной причиной
 * (пауза по решению оператора, а не по покрытию), он придёт сюда значением, а
 * не текстом, и разбор причины останется в одном месте.
 */
export type IntakeState = 'open' | 'paused' | 'sent';

/** Покрытие клиентских средств цело по всем валютам. */
export function intakeOpen(): boolean {
  return coverage(worldJournal()).every((item) => item.covered);
}

/**
 * Положение формы на экране.
 *
 * `state` в адресе — тот же приём, что у остальных экранов обхода
 * (`?state=empty`, `?state=error`): состояние воспроизводится ссылкой, иначе
 * его не снять ни скриншотом, ни проверкой. Остановка приёма при этом **не
 * снимается** параметром: `?state=sent` при нарушенном покрытии всё равно даёт
 * «не принимаем», потому что в этот момент заявку действительно некуда деть.
 */
export function intakeState(query: string | undefined, open: boolean): IntakeState {
  if (query === 'paused' || !open) return 'paused';
  if (query === 'sent') return 'sent';
  return 'open';
}
